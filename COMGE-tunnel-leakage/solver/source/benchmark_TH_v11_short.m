function comparison=benchmark_TH_v11_short(days)
%BENCHMARK_TH_V11_SHORT Compare v10/v11 from identical year-19 fields.
if nargin<1, days=30; end
root=fileparts(mfilename('fullpath'));
s=load(fullfile(root,'segment_v10_iteration_stress20_20260923','year_19.mat'),'out');
previous=s.out;
p=previous.parameters;
p.mesh=previous.mesh;
p.initial=struct('mode','fields','T',previous.T,'h',previous.h,'startDay',19*365);
p.durationDays=days; p.outputEveryDays=days;
p.saveOutput=false; p.plot=false; p.verbose=false; p.mechanics.enable=false;
started=tic; baseline=TH_2D_segment_v10(p); t10=toc(started);
started=tic; candidate=TH_2D_segment_v11(p); t11=toc(started);
comparison=struct('days',days,'v10Seconds',t10,'v11Seconds',t11, ...
    'speedup',t10/t11,'v10Steps',baseline.solverWork.acceptedSteps, ...
    'v11Steps',candidate.solverWork.acceptedSteps, ...
    'v10Jacobians',baseline.solverWork.jacobianBuilds, ...
    'v11Jacobians',candidate.solverWork.jacobianBuilds, ...
    'maxEndDeltaT_C',max(abs(candidate.T-baseline.T)), ...
    'maxEndDeltaH_m',max(abs(candidate.h-baseline.h)), ...
    'leakV10_L_per_m',1000*baseline.leakage.totalVolume_m3_per_m, ...
    'leakV11_L_per_m',1000*candidate.leakage.totalVolume_m3_per_m, ...
    'leakRelativePercent',100*abs(candidate.leakage.totalVolume_m3_per_m- ...
    baseline.leakage.totalVolume_m3_per_m)/max(baseline.leakage.totalVolume_m3_per_m,eps), ...
    'maxV11ScaledResidual',max(candidate.history(:,11)), ...
    'maxV11WaterError_m2',max(abs(candidate.history(:,8))), ...
    'maxV11EnergyError_J_per_m',max(abs(candidate.history(:,9))));
disp(comparison);
end
