function comparison=benchmark_TH_v12_broyden_30d(outputFolder)
%BENCHMARK_TH_V12_BROYDEN_30D Same-state short A/B on the real mesh.
root=fileparts(mfilename('fullpath'));
if nargin<1 || isempty(outputFolder)
    outputFolder=fullfile(root,'v12_broyden_30d_20260923');
end
if ~isfolder(outputFolder), mkdir(outputFolder); end
s=load(fullfile(root,'segment_v10_iteration_stress20_20260923','year_19.mat'),'out');
previous=s.out;
p=previous.parameters;
p.mesh=previous.mesh;
p.initial=struct('mode','fields','T',previous.T,'h',previous.h,'startDay',19*365);
p.durationDays=30; p.outputEveryDays=30;
p.saveOutput=false; p.plot=false; p.verbose=false; p.mechanics.enable=false;
methods={'TH_2D_segment_v11','TH_2D_segment_v12'};
outputs=cell(2,1); elapsed=zeros(2,1);
for k=1:2
    started=tic;
    outputs{k}=feval(methods{k},p);
    elapsed(k)=toc(started);
    out=outputs{k}; elapsed_s=elapsed(k); %#ok<NASGU>
    assert(isequal(out.initialX,[previous.T;previous.h]));
    assert(abs(out.timeDay-(19*365+30))<1e-8);
    assert(abs(sum(out.history(:,2))-30)<1e-8);
    save(fullfile(outputFolder,sprintf('%s_30d.mat',methods{k})), ...
        'out','elapsed_s','-v7');
    fprintf('%s: %.3f s, %d steps/%d rejects, %d Newton, %d J/LU, %d linear, leak %.9f L/m\n', ...
        methods{k},elapsed(k),out.solverWork.acceptedSteps, ...
        out.solverWork.rejectedSteps,out.solverWork.nonlinearIterations, ...
        out.solverWork.jacobianBuilds,out.solverWork.linearSolves, ...
        1000*out.leakage.totalVolume_m3_per_m);
end
a=outputs{1}; b=outputs{2};
comparison=table(string(methods(:)),elapsed, ...
    [a.solverWork.acceptedSteps;b.solverWork.acceptedSteps], ...
    [a.solverWork.rejectedSteps;b.solverWork.rejectedSteps], ...
    [a.solverWork.nonlinearIterations;b.solverWork.nonlinearIterations], ...
    [a.solverWork.jacobianBuilds;b.solverWork.jacobianBuilds], ...
    [a.solverWork.linearSolves;b.solverWork.linearSolves], ...
    [a.solverWork.residualEvaluations;b.solverWork.residualEvaluations], ...
    1000*[a.leakage.totalVolume_m3_per_m;b.leakage.totalVolume_m3_per_m], ...
    [max(a.history(:,11));max(b.history(:,11))], ...
    [max(abs(a.history(:,8)));max(abs(b.history(:,8)))], ...
    [max(abs(a.history(:,9)));max(abs(b.history(:,9)))], ...
    'VariableNames',{'Solver','Elapsed_s','Accepted','Rejected','NewtonIterations', ...
    'JacobianBuilds','LinearSolves','ResidualEvaluations','Leak_L_per_m', ...
    'MaxScaledResidual','MaxWaterDefect_m2_per_m','MaxEnergyDefect_J_per_m'});
writetable(comparison,fullfile(outputFolder,'comparison.csv'));
differences=struct('elapsedSpeedup',elapsed(1)/elapsed(2), ...
    'maxEndDeltaT_C',max(abs(a.T-b.T)), ...
    'maxEndDeltaH_m',max(abs(a.h-b.h)), ...
    'leakRelativePercent',100*abs(a.leakage.totalVolume_m3_per_m- ...
    b.leakage.totalVolume_m3_per_m)/max(a.leakage.totalVolume_m3_per_m,eps), ...
    'dailyLeakL1Percent',100*sum(abs(a.leakage.dailyTotalVolume_m3_per_m- ...
    b.leakage.dailyTotalVolume_m3_per_m))/max(a.leakage.totalVolume_m3_per_m,eps));
save(fullfile(outputFolder,'differences.mat'),'differences','-v7');
disp(comparison); disp(differences);
end
