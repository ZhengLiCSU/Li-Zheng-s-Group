function settings = joint_freeze_defaults(overrides)
%JOINT_FREEZE_DEFAULTS Settings for reversible microchannel ice blockage.
%   S = JOINT_FREEZE_DEFAULTS() keeps the legacy constant-conductance law
%   disabled. Set S.enabled = true to apply the new constitutive law.
%   S = JOINT_FREEZE_DEFAULTS(OVERRIDES) accepts a partial scalar struct.
%
%   flowWeightedRadius_m is the median of the r^4-weighted conducting
%   capillary-radius distribution, not a visible joint opening or the finite
%   numerical support width. Radius and logRadiusStd may be scalar or one
%   value per joint. Their defaults are illustrative, not gasket test data.
%   quadraturePoints describes midpoint sampling along the lining thickness;
%   JOINT_FREEZE_CONDUCTANCE uses the actual number of supplied columns.
settings = struct( ...
    'enabled',false, ...
    'iceEnabled',true, ...
    'viscosityEnabled',true, ...
    'heatExchangeEnabled',true, ... % equilibrium liquid sensible heat along path
    'quadraturePoints',8, ...
    'referenceTemperature_C',20, ...
    'flowWeightedRadius_m',1e-6, ...
    'flowWeightedRadiusProfile_m',[], ... % fixed geometry, joint-by-path sample
    'logRadiusStd',0.7, ...
    'bulkFreezingTemperature_C',0, ...
    'interfacialEnergy_J_m2',0.029, ...
    'iceDensity_kg_m3',917, ...
    'latentHeat_J_kg',3.35e5, ...
    'meltingTemperature_K',273.15);
if nargin == 0 || isempty(overrides)
    return
end
assert(isstruct(overrides) && isscalar(overrides), ...
    'joint_freeze_defaults:InvalidOverrides', ...
    'Overrides must be a scalar structure.');
names = fieldnames(overrides);
for k = 1:numel(names)
    assert(isfield(settings,names{k}), ...
        'joint_freeze_defaults:UnknownSetting', ...
        'Unknown joint-freezing setting: %s.',names{k});
    settings.(names{k}) = overrides.(names{k});
end
end
