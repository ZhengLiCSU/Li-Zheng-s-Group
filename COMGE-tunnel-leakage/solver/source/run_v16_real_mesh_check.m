function report=run_v16_real_mesh_check(caseName)
%RUN_V16_REAL_MESH_CHECK Full research-mesh monolithic short freeze test.
if nargin<1, caseName='real_mesh'; end
assert(ischar(caseName)&&~isempty(regexp(caseName,'^[a-zA-Z0-9_]+$','once')), ...
    'Use a simple case name for a fresh verification folder.');
root=fileparts(mfilename('fullpath')); addpath(root); maxNumCompThreads(4);
folder=fullfile(root,'v16_verification_20260930',caseName);
assert(~isfile(fullfile(folder,'verification.mat')),'Verification already exists.');
if ~isfolder(folder), mkdir(folder); end
o=joint_supply_th_model(struct('durationDays',2,'dtMax',.25*86400, ...
    'outputEveryDays',1,'plot',false,'saveOutput',true,'verbose',true, ...
    'outputPrefix',fullfile(folder,'thm'),'mechanics',struct('enable',false)));
started=tic; out=TH_2D_segment_v16(o); elapsed=toc(started);
report=struct('durationDays',out.timeDay,'elapsed_s',elapsed, ...
    'version',out.version,'unknowns',numel(out.finalX), ...
    'acceptedSteps',out.solverWork.acceptedSteps,'rejectedSteps',out.solverWork.rejectedSteps, ...
    'maximumWaterDefect_m2',max(abs(out.history(:,8))), ...
    'maximumEnergyDefect_Jm',max(abs(out.history(:,9))), ...
    'maximumFreeMechanicalResidual_Nm',out.mechanics.maximumFreeResidual_N_per_m, ...
    'maximumVolumetricStrain',max(abs(out.state.elementVolumetricStrain)), ...
    'maximumPrincipalStrain',out.mechanics.soilStrainDiagnostics.maxAbsPrincipalStrain, ...
    'maximumDisplacementGradient',out.mechanics.soilStrainDiagnostics.maxGradientNorm, ...
    'maximumPorosityChange',max(abs(out.state.currentPorosity-out.parameters.porosity)), ...
    'minimumTemperature_C',min(out.T),'maximumIceVolumeFraction',max(out.state.thetaI), ...
    'leak_Lm',1000*out.leakage.totalVolume_m3_per_m, ...
    'omittedSlitVolumeFraction',out.mechanics.omittedNewChannelVolumeFraction);
assert(out.timeDay==2&&out.leakage.bodyVolume_m3_per_m==0);
assert(report.maximumWaterDefect_m2<1e-6&&report.maximumEnergyDefect_Jm<100);
assert(report.maximumFreeMechanicalResidual_Nm<.1);
assert(report.maximumVolumetricStrain<out.parameters.thm.maximumVolumetricStrain);
save(fullfile(folder,'verification.mat'),'report','-v7'); disp(report);
end
