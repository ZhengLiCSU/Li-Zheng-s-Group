function result=benchmark_TH_v11_full20(outputFolder,dtMaxDays,meshFile)
%BENCHMARK_TH_V11_FULL20 Time a 20-year v11 TH sample against saved v10.
% Annual files permit resuming a long benchmark after interruption. The
% physics, mesh, solver tolerance, and year-by-year restart match the v10
% stress run. saveOutput=false skips only redundant monthly checkpoints.
root=fileparts(mfilename('fullpath'));
if nargin<1 || isempty(outputFolder)
    outputFolder=fullfile(root,'segment_v11_full20_benchmark');
end
if nargin<2, dtMaxDays=1; end
assert(isscalar(dtMaxDays) && dtMaxDays>=1 && isfinite(dtMaxDays));
if nargin<3 || isempty(meshFile)
    meshFile=fullfile(root,'example_mesh_repaired_interface.mat');
end
meshData=load(meshFile);
if ~isfolder(outputFolder), mkdir(outputFolder); end
baseline=readtable(fullfile(root, ...
    'segment_v10_iteration_stress20_20260923','yearly_step_audit.csv'));
assert(height(baseline)==20 && isequal(baseline.Year,(1:20)'), ...
    'The archived v10 reference must contain all 20 years.');
o=struct('meshFile',meshFile, ...
    'durationDays',365,'outputEveryDays',365/12,'plot',false, ...
    'verbose',false,'saveOutput',false);
o.initial=struct('mode','profile','surfaceT',-1,'gradient',.006);
o.mechanics=struct('enable',false);
o.leakage=struct('segmentCount',6,'segmentStartAngleRad',0, ...
    'interiorHead',0,'jointAnglesRad',[], ...
    'jointWidth_m',[],'jointConductance',[],'jointEntryHead',[]);
o.dtInitial=.1*86400; o.dtMax=dtMaxDays*86400; o.dtMin=86400/16384;
o.solver=struct('fd',1e-8,'maxIter',60,'tol',2e-8, ...
    'jacobianReuse',4,'jacobianRefreshRatio',.65, ...
    'dtTargetNewtonFraction',.4,'dtAcceptedGrowthFloor',1.05, ...
    'dtHighIterationFraction',.75,'dtGrowthSafety',1.10, ...
    'dtGrowthMax',1.8);
summary=zeros(20,16);
previous=[];
for year=1:20
    yearFile=fullfile(outputFolder,sprintf('year_%02d.mat',year));
    if isfile(yearFile)
        saved=load(yearFile,'out','elapsed_s');
        assert(isfield(saved,'out') && isfield(saved,'elapsed_s'), ...
            'Existing benchmark year file is incomplete.');
        out=saved.out; elapsed_s=saved.elapsed_s;
    else
        if ~isempty(previous)
            o.mesh=previous.mesh;
            o.initial=struct('mode','fields','T',previous.T, ...
                'h',previous.h,'startDay',(year-1)*365);
        else
            o.initial.startDay=0;
        end
        started=tic;
        out=TH_2D_segment_v11(o);
        elapsed_s=toc(started);
        save(yearFile,'out','elapsed_s','-v7');
    end
    assert(contains(out.version,'TH_v11') && ...
        abs(out.parameters.dtMax-dtMaxDays*86400)<1e-9, ...
        'Existing benchmark year used another solver or dtMax.');
    assert(isequal(out.mesh.pAll,meshData.pAll) && ...
        isequal(out.mesh.tSoil,meshData.tSoil), ...
        'Existing benchmark year used another mesh.');
    assert(abs(out.timeDay-year*365)<1e-7 && ...
        abs(sum(out.history(:,2))-365)<1e-6 && ...
        out.solverWork.acceptedSteps==size(out.history,1), ...
        'Benchmark year does not cover 365 days.');
    if ~isempty(previous)
        assert(isequal(out.initialX,[previous.T;previous.h]), ...
            'Year-to-year fields are discontinuous.');
    end
    h=out.history;
    leak=1000*out.leakage.totalVolume_m3_per_m;
    relative=100*abs(leak-baseline.Leak_L_per_m(year))/ ...
        baseline.Leak_L_per_m(year);
    reference=load(fullfile(root,'segment_v10_iteration_stress20_20260923', ...
        sprintf('year_%02d.mat',year)),'out');
    ref=reference.out;
    sameMesh=isequal(ref.pAll,out.pAll) && ...
        isequal(ref.soilNodes,out.soilNodes);
    monthlyDiff=1000*max(abs(out.leakage.monthlyTotalVolume_m3_per_m(:)- ...
        ref.leakage.monthlyTotalVolume_m3_per_m(:)));
    dailyDiff=100*sum(abs(out.leakage.dailyTotalVolume_m3_per_m(:)- ...
        ref.leakage.dailyTotalVolume_m3_per_m(:)))/ ...
        ref.leakage.totalVolume_m3_per_m;
    roiT=NaN; roiHead=NaN;
    if sameMesh
        roi=hypot(out.pAll(:,1)-out.mesh.xc, ...
            out.pAll(:,2)-out.mesh.yc)<=16;
        roiH=roi(out.soilNodes);
        roiT=max(abs(out.T(roi)-ref.T(roi)));
        roiHead=max(abs(out.h(roiH)-ref.h(roiH)));
    end
    segment=out.leakage.volumeBySegment_m3_per_m(:);
    refSegment=ref.leakage.volumeBySegment_m3_per_m(:);
    segmentRelative=100*max(abs(segment-refSegment)./max(refSegment,1e-6));
    summary(year,:)=[year elapsed_s leak relative size(h,1) ...
        out.solverWork.rejectedSteps median(h(:,2)) min(h(:,2)) ...
        max(abs(h(:,8))) max(abs(h(:,9))) max(h(:,11)) ...
        monthlyDiff dailyDiff roiT roiHead segmentRelative];
    fprintf('v11 year %02d: %.3f L/m (v10 difference %.4g%%), %.1f s\n', ...
        year,leak,relative,elapsed_s);
    previous=out;
    audit=array2table(summary(1:year,:), ...
        'VariableNames',{'Year','Elapsed_s','Leak_L_per_m', ...
        'RelativeToV10_percent','Accepted','Rejected','MedianDt_day', ...
        'MinDt_day','MaxAbsWaterDefect_m2_per_m', ...
        'MaxAbsEnergyDefect_J_per_m','MaxScaledResidual', ...
        'MaxMonthlyLeakDiff_L_per_m','DailyLeakL1RelativePercent', ...
        'RoiMaxEndDeltaT_C','RoiMaxEndDeltaH_m', ...
        'MaxSegmentAnnualRelativePercent'});
    writetable(audit,fullfile(outputFolder,'yearly_benchmark.csv'));
end
result=struct('yearly',audit,'elapsed_s',sum(audit.Elapsed_s), ...
    'dtMaxDays',dtMaxDays, ...
    'meshFile',meshFile,'thermalDof',numel(previous.T), ...
    'hydraulicDof',numel(previous.h), ...
    'year20Leak_L_per_m',audit.Leak_L_per_m(end), ...
    'year20RelativeToV10_percent',audit.RelativeToV10_percent(end), ...
    'year20',previous,'v10Year20Leak_L_per_m',baseline.Leak_L_per_m(end));
save(fullfile(outputFolder,'benchmark_result.mat'),'result','-v7');
end
