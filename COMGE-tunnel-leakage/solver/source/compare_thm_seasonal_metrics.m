function comparison=compare_thm_seasonal_metrics(coarse,fine)
%COMPARE_THM_SEASONAL_METRICS Explicit denominators and seasonal diagnostics.
% No small monthly leakage is hidden behind an annual denominator. Zero
% fine volume yields NaN relative errors; absolute differences remain.
q=fine.annual_L_m;m=fine.monthly_L_m;
monthlyAbsolute=abs(coarse.monthly_L_m-m);monthlyRelative=NaN(12,1);
nonzero=m>0;monthlyRelative(nonzero)=monthlyAbsolute(nonzero)./m(nonzero);
annual=NaN;monthlyAnnual=NaN(12,1);dailyNorm=NaN;peakError=NaN;
if q>0
    annual=abs(coarse.annual_L_m-q)/q;monthlyAnnual=monthlyAbsolute/q;
    dailyNorm=sum(abs(coarse.daily.actual_L_m-fine.daily.actual_L_m))/q;
end
if fine.peakDaily_L_m>0, peakError=abs(coarse.peakDaily_L_m-fine.peakDaily_L_m)/fine.peakDaily_L_m;end
comparison=struct('annualDifferenceRelativeToFine',annual, ...
    'monthlyAbsoluteDifference_L_m',monthlyAbsolute, ...
    'monthlyDifferenceRelativeToFineMonth',monthlyRelative, ...
    'monthlyDifferenceRelativeToFineAnnual',monthlyAnnual, ...
    'dailyAbsoluteDifferenceSumRelativeToFineAnnual',dailyNorm, ...
    'peakDailyRelativeDifference',peakError, ...
    'peakDayDifference_days',coarse.peakDailyDay-fine.peakDailyDay, ...
    'firstActiveDayDifference_days',coarse.firstActiveDay-fine.firstActiveDay, ...
    'lastActiveDayDifference_days',coarse.lastActiveDay-fine.lastActiveDay, ...
    'scope','Conditional discretization differences; no experimental validation or automatic accuracy claim.');
end
