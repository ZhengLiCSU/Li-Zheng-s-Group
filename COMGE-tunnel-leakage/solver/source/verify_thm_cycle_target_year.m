function report=verify_thm_cycle_target_year(caseFolder,targetYear)
%VERIFY_THM_CYCLE_TARGET_YEAR Conditional half-step recomputation, years2..20.
% Uses the identical preceding COMPLETE X, installed U/T and local cycle
% memory. It does not produce a second complete fine history. Writes only
% to a new conditional folder, retaining original yearly archives.
validateattributes(targetYear,{'numeric'},{'scalar','integer','>=',2,'<=',20});
caseFolder=char(caseFolder);
if ~java.io.File(caseFolder).isAbsolute(),caseFolder=fullfile(pwd,caseFolder);end
caseFolder=char(java.io.File(caseFolder).getCanonicalPath());
saved=load(fullfile(caseFolder,sprintf('year_%02d_annual_results.mat',targetYear)),'out');
coarse=saved.out;
assert(isfield(coarse,'jointCycleDamage')&&coarse.jointCycleDamage.enabled, ...
    'JointCycleRefinement:Case','Require a complete evolving-cycle case.');
cpFile=fullfile(caseFolder,sprintf('year_%02d_checkpoint.mat',targetYear-1));
seed=load(cpFile,'checkpoint');
assert(abs(coarse.timeDay-targetYear*365)<1e-6 ...
    &&abs(seed.checkpoint.time/86400-(targetYear-1)*365)<1e-6 ...
    &&isequal(coarse.initialX,seed.checkpoint.X) ...
    &&isequaln(coarse.jointCycleDamage.initialMemory,seed.checkpoint.jointCycleMemory), ...
    'JointCycleRefinement:Seed','Target year must inherit the preceding complete checkpoint and memory.');
folder=fullfile(caseFolder,sprintf('conditional_year%d_dtHalf',targetYear));
assert(~isfolder(folder),'JointCycleRefinement:Exists','Use the existing evidence; do not overwrite its conditional folder.');
mkdir(folder);
p=coarse.parameters;p.initial=struct('mode','checkpoint','checkpointFile',cpFile);
p.dtMax=p.dtMax/2;p.solver.dtMaxByMonth_days=p.solver.dtMaxByMonth_days/2;
p.dtInitial=min(p.dtInitial,p.dtMax);
p.outputPrefix=fullfile(folder,sprintf('year%d_dtHalf',targetYear));
p.saveOutput=true;p.plot=false;p.verbose=false;
metadata=struct('targetYear',targetYear,'sourceCase',caseFolder, ...
    'checkpointFile',cpFile,'seedX',seed.checkpoint.X, ...
    'seedMemory',seed.checkpoint.jointCycleMemory,'parameters',p, ...
    'scope','Conditional target-year refinement; no full-history convergence claim.');
save(fullfile(folder,'refinement_metadata.mat'),'metadata','-v7');
threads=maxNumCompThreads;cleanup=onCleanup(@()maxNumCompThreads(threads));
maxNumCompThreads(4);timer=tic;fine=TH_2D_segment_v16(p);elapsed=toc(timer);
audit=audit_joint_cycle_damage(fine);
bothZero=coarse.leakage.totalVolume_m3_per_m==0&&fine.leakage.totalVolume_m3_per_m==0;
if fine.leakage.totalVolume_m3_per_m>0
    annualError=abs(coarse.leakage.totalVolume_m3_per_m/fine.leakage.totalVolume_m3_per_m-1);
    monthlyOverAnnual=max(abs(coarse.leakage.monthlyTotalVolume_m3_per_m ...
        -fine.leakage.monthlyTotalVolume_m3_per_m))/fine.leakage.totalVolume_m3_per_m;
    errorGate=annualError<=.01&&monthlyOverAnnual<=.01;
else
    annualError=NaN;monthlyOverAnnual=NaN;
    errorGate=bothZero&&all(coarse.leakage.monthlyTotalVolume_m3_per_m==0) ...
        &&all(fine.leakage.monthlyTotalVolume_m3_per_m==0);
end
report=struct('passed',false,'targetYear',targetYear, ...
    'annualRelativeFineError',annualError,'maxMonthlyDifferenceOverFineAnnual',monthlyOverAnnual, ...
    'bothAnnualLeakageExactlyZero',bothZero, ...
    'coarseQ_L_m',1000*coarse.leakage.totalVolume_m3_per_m, ...
    'fineQ_L_m',1000*fine.leakage.totalVolume_m3_per_m, ...
    'initialXExact',isequal(fine.initialX,seed.checkpoint.X), ...
    'initialMemoryExact',isequaln(fine.jointCycleDamage.initialMemory,seed.checkpoint.jointCycleMemory), ...
    'installedReferenceExact',isequal(fine.mechanics.referenceU,seed.checkpoint.mechanicalReference.U) ...
    &&isequal(fine.mechanics.referenceTemperature,seed.checkpoint.mechanicalReference.T), ...
    'physicalSignatureExact',isequaln(thm_constitutive_signature(fine.parameters),seed.checkpoint.signature), ...
    'localCountsExact',isequal(fine.jointCycleDamage.finalMemory.cycleCount,coarse.jointCycleDamage.finalMemory.cycleCount), ...
    'maxDamageDifference',max(abs(fine.jointCycleDamage.appliedSeverity-coarse.jointCycleDamage.appliedSeverity)), ...
    'maxWaterDefect_m2',max(abs(fine.history(:,8))), ...
    'maxHeatDefect_J_m',max(abs(fine.history(:,9))), ...
    'solverWork',fine.solverWork,'elapsed_s',elapsed,'cycleAudit',audit, ...
    'scope','Same preceding CP, physics, mesh and integration; conditional target year only. Monthly difference is normalized by fine ANNUAL volume.');
report.passed=errorGate&&audit.passed ...
    &&report.initialXExact&&report.initialMemoryExact&&report.installedReferenceExact ...
    &&report.physicalSignatureExact&&report.localCountsExact ...
    &&report.maxWaterDefect_m2<1e-7&&report.maxHeatDefect_J_m<10;
save(fullfile(folder,'literature_time_refinement_report.mat'),'report','-v7');
assert(report.passed,'JointCycleRefinement:Failed','Refinement gate failed. Unchanged evidence retained.');
end
