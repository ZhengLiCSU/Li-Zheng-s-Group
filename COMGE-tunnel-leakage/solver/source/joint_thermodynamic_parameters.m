function p = joint_thermodynamic_parameters(overrides)
%JOINT_THERMODYNAMIC_PARAMETERS Parameters for the independent slit branch.
% This is an ideal saturated, planar water/ice slit, not a calibrated gasket.
% Stiffness and geometry below are demonstration values. Ice/liquid density
% differences are physical; capillary shift and irreversible damage are off.
arguments
    overrides (1,1) struct = struct()
end
p = struct('rhoWater',1000,'rhoIce',917,'bulkWater_Pa',2.2e9, ...
    'bulkIce_Pa',9e9,'heatWater_JkgK',4180,'heatIce_JkgK',2100, ...
    'latentHeat_Jkg',334e3,'meltingTemperature_K',273.15, ...
    'capillaryShift_Jkg',0,'aperture0_m',5e-6,'wetAreaFraction',1, ...
    'normalStiffness_Pam',1e12,'contactStiffness_Pam',1e14, ...
    'referenceGap_m',0,'externalTraction_Pa',0, ...
    'viscosity_Pas',1.8e-3,'phaseViscosity_Jm2skg2',0, ...
    'maximumCompression',0.05,'minimumPressure_Pa',-5e4);
names = fieldnames(overrides);
for k = 1:numel(names)
    assert(isfield(p,names{k}),'JointThermo:UnknownParameter', ...
        'Unknown thermodynamic parameter: %s.',names{k});
    p.(names{k}) = overrides.(names{k});
end
positive = {'rhoWater','rhoIce','bulkWater_Pa','bulkIce_Pa', ...
    'heatWater_JkgK','heatIce_JkgK','latentHeat_Jkg', ...
    'meltingTemperature_K','aperture0_m','wetAreaFraction', ...
    'normalStiffness_Pam','viscosity_Pas','maximumCompression'};
for k = 1:numel(positive)
    validateattributes(p.(positive{k}),{'double'}, ...
        {'scalar','real','finite','positive'},mfilename,positive{k});
end
nonnegative = {'contactStiffness_Pam','phaseViscosity_Jm2skg2', ...
    'capillaryShift_Jkg'};
for k = 1:numel(nonnegative)
    validateattributes(p.(nonnegative{k}),{'double'}, ...
        {'scalar','real','finite','nonnegative'},mfilename,nonnegative{k});
end
validateattributes(p.referenceGap_m,{'double'},{'scalar','real','finite'});
validateattributes(p.externalTraction_Pa,{'double'},{'scalar','real','finite'});
validateattributes(p.minimumPressure_Pa,{'double'},{'scalar','real','finite'});
assert(p.wetAreaFraction<=1 && p.maximumCompression<1, ...
    'JointThermo:ParameterDomain','Area fraction and compression limit must be below one.');
assert(p.rhoIce<p.rhoWater,'JointThermo:DensityOrder', ...
    'This water/ice branch requires rhoIce < rhoWater.');
end
