function report=evaluate_joint_microchannel_observations(data,law,provenance)
%EVALUATE_JOINT_MICROCHANNEL_OBSERVATIONS Fixed-defect isothermal p-Q check.
% DATA table columns: temperature_C, pressureDrop_Pa, measured_L_day_m.
% LAW: referenceConductance_m_s, entryHead_m, freezeSettings. No parameters
% are fitted here. Fixed geometry, water rho=1000 kg/m3, g=9.81 m/s2.
% PROVENANCE.kind: experiment / independent_numerical / synthetic, and
% source (DOI/dataset identifier). Changing gasket geometry or breakdown
% pressure requires a different constitutive law; this is not its validator.
assert(istable(data)&&all(ismember({'temperature_C','pressureDrop_Pa','measured_L_day_m'}, ...
    data.Properties.VariableNames))&&height(data)>0, ...
    'JointObservation:Data','Supply a nonempty table with the three unit-labelled columns.');
values=data{:,{'temperature_C','pressureDrop_Pa','measured_L_day_m'}};
assert(isnumeric(values)&&isreal(values)&&all(isfinite(values(:))) ...
    &&all(values(:,2)>=0)&&all(values(:,3)>=0), ...
    'JointObservation:Values','Observations must be finite, with nonnegative pressure drop and leakage.');
assert(isstruct(provenance)&&isscalar(provenance)&&all(isfield(provenance,{'kind','source'})) ...
    &&any(strcmp(provenance.kind,{'experiment','independent_numerical','synthetic'})) ...
    &&strlength(string(provenance.source))>0, ...
    'JointObservation:Provenance','Explicit data kind and source are mandatory.');
assert(isstruct(law)&&isscalar(law)&&all(isfield(law, ...
    {'referenceConductance_m_s','entryHead_m','freezeSettings'})) ...
    &&isscalar(law.referenceConductance_m_s)&&isfinite(law.referenceConductance_m_s) ...
    &&law.referenceConductance_m_s>=0&&isscalar(law.entryHead_m) ...
    &&isfinite(law.entryHead_m)&&law.entryHead_m>=0, ...
    'JointObservation:Law','Specify fixed conductance, entry head and freezing settings.');
settings=joint_freeze_defaults(law.freezeSettings);
assert(isscalar(settings.flowWeightedRadius_m)&&isscalar(settings.logRadiusStd), ...
    'JointObservation:SingleJoint','Use one fixed joint radius distribution for this observation set.');
factor=joint_freeze_conductance(values(:,1),settings);
predicted=law.referenceConductance_m_s*factor.*max(values(:,2)/(1000*9.81)-law.entryHead_m,0)*86400*1000;
residual=predicted-values(:,3);scale=max(values(:,3))-min(values(:,3));normalized=NaN;
if scale>0, normalized=sqrt(mean(residual.^2))/scale; end
report=struct('schemaVersion',1,'provenance',provenance,'law',law, ...
    'comparison',table(values(:,1),values(:,2),values(:,3),predicted,residual, ...
    'VariableNames',{'temperature_C','pressureDrop_Pa','measured_L_day_m','predicted_L_day_m','residual_L_day_m'}), ...
    'rmse_L_day_m',sqrt(mean(residual.^2)),'rangeNormalizedRMSE',normalized, ...
    'isExperimentalComparison',strcmp(provenance.kind,'experiment'), ...
    'scope','Fixed existing microchannel at uniform temperature; no calibration, moving gap, gasket failure or automatic acceptance.');
end
