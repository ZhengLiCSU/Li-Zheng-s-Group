function summary=benchmark_joint_only_20y(outputFolder,dtMaxDays)
%BENCHMARK_JOINT_ONLY_20Y Full 20-year eight-segment joint-only TH run.
% Creates a new checkpoint set, or resumes one with the same model/dtMax.
% The default hydraulic joint parameters are examples, not field estimates.
root=fileparts(mfilename('fullpath'));
if nargin<1 || isempty(outputFolder)
    outputFolder=fullfile(root,'segment_year20_jointonly_8segment_illustrative');
end
if nargin<2, dtMaxDays=4; end
assert(isscalar(dtMaxDays)&&isfinite(dtMaxDays)&&dtMaxDays>0&&dtMaxDays<=4);
user=struct('outputFolder',outputFolder, ...
    'model',struct('dtMax',dtMaxDays*86400));
user.resume=isfile(fullfile(outputFolder,'spinup_progress.mat'));
wasResumed=user.resume;
started=tic;
r=run_TH_segment_year20_jointonly(user);
wallTime_s=toc(started);
assert(r.completedYears==20,'The complete 20-year sample did not finish.');
fullSampleWallTime_s=wallTime_s;
if wasResumed, fullSampleWallTime_s=NaN; end
leak=r.lastYear.leakage;
h=r.lastYear.history;
summary=struct('completedYears',r.completedYears, ...
    'dtMaxDays',dtMaxDays,'resumed',wasResumed, ...
    'wallTimeThisInvocation_s',wallTime_s, ...
    'fullSampleWallTime_s',fullSampleWallTime_s, ...
    'year20Total_L_per_m',r.year20AnnualLeakage_L_per_m, ...
    'year20Joint_L_per_m',r.year20JointLeakage_L_per_m, ...
    'year20Body_L_per_m',r.year20BodyLeakage_L_per_m, ...
    'year20ByJoint_L_per_m',1000*leak.volumeByJoint_m3_per_m, ...
    'year20ByMonth_L_per_m',1000*leak.monthlyTotalVolume_m3_per_m, ...
    'acceptedSteps',size(h,1), ...
    'rejectedSteps',r.lastYear.solverWork.rejectedSteps, ...
    'minimumStepDays',min(h(:,2)), ...
    'maximumWaterDefect_m2',max(abs(h(:,8))), ...
    'maximumEnergyDefect_J_per_m',max(abs(h(:,9))));
save(fullfile(outputFolder,'joint_only_20y_summary.mat'),'summary','-v7');
export_joint_only_year20(outputFolder);
fprintf('Joint-only year 20: %.6f L/m (body %.6f L/m), %.1f s; min dt %.5g d.\n', ...
    summary.year20Joint_L_per_m,summary.year20Body_L_per_m, ...
    summary.wallTimeThisInvocation_s,summary.minimumStepDays);
end
