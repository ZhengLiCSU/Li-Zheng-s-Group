function study=run_joint_supply_radial_check(caseName)
%RUN_JOINT_SUPPLY_RADIAL_CHECK Final-year 8-versus-16 path quadrature check.
% STUDY=RUN_JOINT_SUPPLY_RADIAL_CHECK defaults to base; supplySeasonal is
% also supported. Both calculations use the same case's own complete
% year-19 fields, same mesh, same physical parameters and one-day maximum
% step. The existing nq=8/day-1 comparison file is required, never inferred.
% This checks final-year radial midpoint integration only; the preceding
% nineteen years retain nq=8. It is not full-history radial convergence.
if nargin<1||isempty(caseName), caseName='base'; end
assert((ischar(caseName)&&isrow(caseName))|| ...
    (isstring(caseName)&&isscalar(caseName)),'Supply one case name.');
caseName=char(caseName);
assert(any(strcmp(caseName,{'base','supplySeasonal'})), ...
    'Select base or supplySeasonal for the final-year radial check.');
root=fileparts(mfilename('fullpath')); addpath(root);
folder=fullfile(root,'joint_supply_study_20260930');
sourceFile=fullfile(folder,caseName,'TH_segment_spinup_results.mat');
referenceFile=fullfile(folder,'year20_timestep_checks',caseName,'dt1_results.mat');
assert(isfile(sourceFile),'Missing complete twenty-year source: %s.',sourceFile);
assert(isfile(referenceFile),'Missing nq=8/day-1 comparison: %s.',referenceFile);
loaded=load(sourceFile,'result'); result=loaded.result;
assert(isstruct(result)&&isfield(result,'completedYears')&&result.completedYears==20 ...
    &&isfield(result,'lastYear')&&isfield(result,'diagnostics')&&isfield(result,'columns'), ...
    'Source must retain its complete own twenty-year v14 history.');
yearColumn=find(strcmp(result.columns,'year'),1);
assert(~isempty(yearColumn)&&isequal(result.diagnostics(:,yearColumn),(1:20)'), ...
    'Source lacks an uninterrupted twenty-year diagnostic record.');
source=result.lastYear; assertCompleteYear(source);
nT=numel(source.T); X=source.initialX(:);
assert(numel(X)==nT+numel(source.h)&&all(isfinite(X)), ...
    'Source lacks its actual complete end-of-year-19 state.');
assert(source.parameters.leakage.jointFreeze.quadraturePoints==8, ...
    'This comparison requires an nq=8 complete-history source.');
loaded=load(referenceFile,'out'); reference=loaded.out; assertCompleteYear(reference);
assert(reference.parameters.leakage.jointFreeze.quadraturePoints==8 ...
    &&abs(reference.parameters.dtMax-86400)<1e-9 ...
    &&isequaln(reference.initialX(:),X), ...
    'The nq=8/day-1 reference must start from this same own year-19 state.');
assertSameMesh(source.mesh,reference.mesh);
assert(isequaln(physicalParameters(source.parameters),physicalParameters(reference.parameters)), ...
    'Reference and source differ in physical parameters or forcing.');

outputFolder=fullfile(folder,'year20_radial_checks');
if ~isfolder(outputFolder), mkdir(outputFolder); end
prefix=fullfile(outputFolder,[caseName '_nq16_dt1']);
opt=source.parameters; opt.mesh=source.mesh;
opt.initial=struct('mode','fields','T',X(1:nT),'h',X(nT+1:end),'startDay',19*365);
opt.leakage.jointFreeze.quadraturePoints=16;
opt.durationDays=365; opt.outputEveryDays=365/12;
opt.dtMax=86400; opt.dtInitial=.1*86400;
opt.mechanics.enable=false; opt.plot=false; opt.verbose=false; opt.saveOutput=true;
opt.outputPrefix=prefix;
previousThreads=maxNumCompThreads(4);
cleanThreads=onCleanup(@()maxNumCompThreads(previousThreads)); %#ok<NASGU>
fprintf('V14 radial check: %s, nq=16/day-1, same own year-19 fields and mesh.\n',caseName);
started=tic; out=TH_2D_segment_v14(opt); elapsed=toc(started);
assertCompleteYear(out); assertSameMesh(source.mesh,out.mesh);
assert(isequaln(out.initialX(:),X),'Radial comparison changed the initial fields.');
expected=physicalParameters(reference.parameters);
expected.leakage.jointFreeze.quadraturePoints=16;
assert(isequaln(physicalParameters(out.parameters),expected), ...
    'Radial comparison changed parameters beyond the quadrature count.');

rows=[metrics(reference,caseName,8,NaN),metrics(out,caseName,16,elapsed)];
comparison=struct2table(rows);
Q16=comparison.Q20_L_per_m(2);
daily8=1000*reference.leakage.dailyTotalVolume_m3_per_m(:);
daily16=1000*out.leakage.dailyTotalVolume_m3_per_m(:);
dailyDifference=sum(abs(daily8-daily16));
comparison.annualDifferenceRelativeToNq16_percent= ...
    100*abs(comparison.Q20_L_per_m-Q16)/max(abs(Q16),realmin);
comparison.dailyL1DifferenceRelativeToNq16_L_per_m=[dailyDifference;0];
comparison.dailyL1RelativeToNq16_percent=[100*dailyDifference/max(abs(Q16),realmin);0];
limitation=['Only year-20 radial midpoint integration is compared, with the same ' ...
    'case-specific year-19 state produced using nq=8. This does not demonstrate ' ...
    'full-history radial integration convergence, spatial convergence, periodic ' ...
    'steady state, physical calibration, or cumulative freeze-thaw damage.'];
metadata=struct('caseName',caseName,'sourceFile',sourceFile,'referenceFile',referenceFile, ...
    'sourceCompletedYears',20,'initialStateSource','same complete lastYear.initialX, end of year 19', ...
    'startDay',19*365,'durationDays',365,'referenceRadialSamples',16, ...
    'maximumStep_day',1,'elapsed_s',elapsed,'limitation',limitation, ...
    'comparison',comparison); %#ok<NASGU>
save([prefix '_results.mat'],'metadata','-append');
csvFile=fullfile(outputFolder,[caseName '_radial_comparison.csv']);
writetable(comparison,csvFile,'Encoding','UTF-8');
phaseDay=(1:365)';
writetable(table(phaseDay,daily8,daily16, ...
    'VariableNames',{'day_of_year_binEnd','nq8_actual_L_per_m','nq16_actual_L_per_m'}), ...
    fullfile(outputFolder,[caseName '_radial_daily.csv']),'Encoding','UTF-8');
study=struct('metadata',metadata,'comparison',comparison,'out',out, ...
    'referenceFile',referenceFile,'resultFile',[prefix '_results.mat'],'comparisonCSV',csvFile);
disp(comparison(:,{'caseName','radialSamples','Q20_L_per_m', ...
    'annualDifferenceRelativeToNq16_percent','dailyL1RelativeToNq16_percent', ...
    'sameT_static_reduction_percent','sameT_seasonal_reduction_percent','elapsed_s'}));
fprintf('%s\n',limitation);
end

function row=metrics(out,name,nq,elapsed)
p=out.parameters; h=out.history; L=p.leakage;
nj=numel(L.jointAnglesRad); c=L.jointConductance(:);
if isscalar(c), c=repmat(c,nj,1); end
assert(numel(c)==nj&&numel(c)==8&&isequal(find(c>0),7), ...
    'The radial study requires joint 7 as its single conducting joint.');
dt=h(:,2)*86400; factor=out.leakage.jointFreeze.factor;
hydraulic=out.leakage.hydraulics;
staticHead=hydraulic.referenceHead_m+hydraulic.waterTableDepth_m-p.waterTableDepth;
staticRate=factor.*c'.*max(staticHead,0);
Q=1000*out.leakage.totalVolume_m3_per_m;
Qstatic=1000*sum(dt.*sum(staticRate,2));
Qseasonal=1000*sum(dt.*sum(hydraulic.unrestrictedRate_m2_per_s,2));
level=NaN;
if isfield(out.mesh,'jointRefinementReport'), level=out.mesh.jointRefinementReport.level; end
row=struct('caseName',string(name),'radialSamples',nq,'maximumStep_day',1, ...
    'Q20_L_per_m',Q,'sameT_static_L_per_m',Qstatic,'sameT_seasonal_L_per_m',Qseasonal, ...
    'sameT_static_reduction_percent',100*(Qstatic-Q)/max(abs(Qstatic),realmin), ...
    'sameT_seasonal_reduction_percent',100*(Qseasonal-Q)/max(abs(Qseasonal),realmin), ...
    'meshRefinementLevel',level,'thermalNodes',numel(out.T),'soilHeadNodes',numel(out.h), ...
    'acceptedSteps',out.solverWork.acceptedSteps,'rejectedSteps',out.solverWork.rejectedSteps, ...
    'elapsed_s',elapsed,'minimumStep_day',min(h(:,2)), ...
    'maximumScaledResidual',max(h(:,11)), ...
    'signedWaterDefect_m2',sum(h(:,8)),'maxAbsWaterDefect_m2',max(abs(h(:,8))), ...
    'signedEnergyDefect_J_per_m',sum(h(:,9)), ...
    'maxAbsEnergyDefect_J_per_m',max(abs(h(:,9))), ...
    'maximumNegativeTransEdges',max(hydraulic.negativeTransEdges));
end

function p=physicalParameters(p)
nonphysical={'mesh','meshFile','durationDays','dtInitial','dtMax','dtMin', ...
    'outputEveryDays','outputPrefix','saveOutput','plot','verbose','initial', ...
    'solver','spinup','mechanics'};
p=rmfield(p,intersect(nonphysical,fieldnames(p)));
end

function assertSameMesh(a,b)
fields={'pAll','tSoil','qTunnelGlobal','qInvertGlobal','tInvertTriGlobal', ...
    'soilTunnelCoupleTable','tunnelInnerRingGlobal','invertBottomRingGlobal', ...
    'invertTopRingGlobal','bInvertTopGlobal'};
for k=1:numel(fields)
    name=fields{k};
    assert(isfield(a,name)==isfield(b,name),'Mesh field inventory changed: %s.',name);
    if isfield(a,name), assert(isequaln(a.(name),b.(name)),'Mesh changed: %s.',name); end
end
end

function assertCompleteYear(out)
assert(isstruct(out)&&isfield(out,'version') ...
    &&strcmp(out.version,'TH_v14_20260930_joint_supply') ...
    &&abs(out.timeDay-20*365)<1e-7,'A complete v14 year-20 result is required.');
h=out.history;
assert(~isempty(h)&&all(isfinite(h(:)))&&all(diff(h(:,1))>0) ...
    &&abs(sum(h(:,2))-365)<1e-6&&abs(h(1,1)-h(1,2)-19*365)<1e-7, ...
    'The accepted twentieth-year history is incomplete.');
assert(numel(out.leakage.dailyTotalVolume_m3_per_m)==365 ...
    &&size(out.leakage.hydraulics.history,1)==size(h,1) ...
    &&size(out.leakage.jointFreeze.history,1)==size(h,1), ...
    'Joint diagnostic or daily histories are incomplete.');
assert(out.parameters.liningK==0&&out.leakage.bodyVolume_m3_per_m==0 ...
    &&abs(sum(out.leakage.volumeByJoint_m3_per_m)-out.leakage.totalVolume_m3_per_m)<1e-9, ...
    'The joint-only volume partition failed.');
end
