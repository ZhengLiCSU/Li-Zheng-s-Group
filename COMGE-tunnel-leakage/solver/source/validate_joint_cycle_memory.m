function validate_joint_cycle_memory(s,nj,nq,c)
%VALIDATE_JOINT_CYCLE_MEMORY Reject incomplete/corrupted internal variables.
c=joint_cycle_damage_defaults(c);
keys={'revision','lastDay','armed','frozen','peakIce','freezeStartDay', ...
    'cycleCount','cumulativeDose','sampleSeverity','targetSeverity','lastIce'};
assert(isstruct(s)&&isscalar(s)&&all(isfield(s,keys)) ...
    &&strcmp(s.revision,'local_ice_cycle_v1_20261002') ...
    &&isscalar(s.lastDay)&&isfinite(s.lastDay),'JointCycle:Memory','Incomplete cycle memory.');
for key={'armed','frozen','peakIce','freezeStartDay','cycleCount','cumulativeDose','sampleSeverity','lastIce'}
    v=s.(key{1});
    assert(isreal(v)&&isequal(size(v),[nj nq]),'JointCycle:Memory','Invalid memory dimensions.');
    if ~strcmp(key{1},'freezeStartDay')
        assert(all(isfinite(v(:))),'JointCycle:Memory','Nonfinite internal state.');
    end
end
assert(islogical(s.armed)&&islogical(s.frozen) ...
    &&~any(s.armed(:)&s.frozen(:))&&all(s.cycleCount(:)>=0) ...
    &&all(s.cycleCount(:)==fix(s.cycleCount(:)))&&all(s.cumulativeDose(:)>=0) ...
    &&all(s.lastIce(:)>=0&s.lastIce(:)<=1)&&all(s.peakIce(:)>=0&s.peakIce(:)<=1) ...
    &&all(isfinite(s.freezeStartDay(s.frozen))) ...
    &&all(s.freezeStartDay(s.frozen)<=s.lastDay) ...
    &&all(isnan(s.freezeStartDay(~s.frozen))), ...
    'JointCycle:Memory','Cycle counters/flags/partial-cycle times are corrupted.');
assert(all(s.cumulativeDose(:)<=s.cycleCount(:)+1e-12) ...
    &&all(s.peakIce(~s.frozen)==0) ...
    &&all(s.peakIce(s.frozen)>=c.freezeFraction) ...
    &&all(s.peakIce(s.frozen)>=s.lastIce(s.frozen)) ...
    &&all(s.lastIce(s.frozen)>c.thawFraction), ...
    'JointCycle:Memory','Dose exceeds completed cycles or partial-cycle extrema are inconsistent.');
D0=expand(c.initialSeverity,nj);rate=expand(c.doseRate,nj);
expected=joint_cycle_severity(s.cumulativeDose,rate,D0);
assert(max(abs(expected-s.sampleSeverity),[],'all')<1e-12 ...
    &&isequal(size(s.targetSeverity),[nj 1]) ...
    &&max(abs(mean(expected,2)-s.targetSeverity))<1e-12, ...
    'JointCycle:Memory','Damage and accumulated dose are inconsistent.');
end
function v=expand(v,n)
v=v(:);if isscalar(v),v=repmat(v,n,1);end
assert(numel(v)==n,'JointCycle:Shape','Settings require scalar or joint vector.');
end
