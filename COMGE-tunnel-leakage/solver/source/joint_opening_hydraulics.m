function [C,dCdg,dCdT,diagnostic]=joint_opening_hydraulics(Cref,gap,Tprofile,options)
%JOINT_OPENING_HYDRAULICS Existing defect plus a separate open-slit branch.
% [C,dCdg,dCdT,D]=joint_opening_hydraulics(Cref,gap,Tprofile,options)
% uses one signed mechanical opening per joint [m]. Cref and C are hydraulic
% head conductances [m/s], so q=C*positiveHead is [m2/s] per axial metre.
% Positive opening permits a NEW smooth parallel-plate passage only at a
% pre-existing defect (Cref>0). Sealed joints stay exactly impermeable.
%
% b=f*max(gap,0), Copen,ref=rho*g*b^3/(12*muRef*pathLength).
% C=Cref*baseMobilityFactor+Copen,ref*openMobilityFactor.
% f is a mechanical-to-connected-hydraulic aperture mapping, NOT a measured
% gasket property. Its safe default is zero; f=1 uses a fully connected
% ideal slit, while a reduced f must be calibrated or labelled illustrative.
% Existing defects retain their original capillary freezing law through
% supplied baseMobilityFactor / baseMobilityDerivative_dT. A diagnostic
% equivalent base aperture is never added to b or used as a capillary radius.
%
% With freezeEnabled=true, the optional slit equilibrium temperature is
% Tf=Tbulk-2*Tm*(gamma_solid-wall-gamma_liquid-wall)/(rhoIce*latent*b).
% wallEnergyDifference_J_m2 defaults to zero (bulk freezing for a macro slit).
% It MUST NOT be replaced automatically by the cylindrical ice-water sigma.
% Uniform-length Tprofile samples form a SERIES path; sampleWeights may
% override their length fractions. A wholly frozen sample blocks this new
% branch. The ideal equilibrium law is binary, not a premelting-film law.
% transitionWidth_C>0 gives an explicitly numerical C1 regularization of
% phase conductance, NOT a calibrated SFCC or a resolved ice-plate thickness.
% No hysteresis, nucleation, salinity, pressure melting, roughness evolution,
% gasket failure, aging, or irreversible damage is introduced.
%
% dCdg is one derivative per joint. dCdT is nj-by-nq for path temperatures,
% including supplied base derivatives. At binary phase switches there is no
% unique classical derivative; the selected derivative is zero. Opening is
% assumed uniform through the thickness; variable contact paths need a
% spatial aperture model instead of averaging their mechanical gap.
% D additionally supplies V=pathLength*b, liquid/ice sample volumes and
% their partial derivatives for a SEPARATE moving-channel inventory. This
% kernel does not add that storage to water/heat equations. In particular,
% closure expels water, so a storage-aware inlet can reverse and requires
% channel-donor heat upwinding and a pressure/storage closure in the caller.
%
% Primary laws: doi:10.1029/WR016i006p01016 (parallel-plate cubic flow);
% doi:10.1063/5.0044330 (slit confinement thermodynamics and wall energies).

if nargin<3 || isempty(Tprofile), Tprofile=[]; end
if nargin<4 || isempty(options), options=struct(); end
assert(isstruct(options)&&isscalar(options),'JointOpeningHydraulics:Options', ...
    'options must be a scalar struct.');
s=struct('openingTransmissionFraction',0,'pathLength_m',.45, ...
    'waterDensity_kg_m3',1000,'gravity_m_s2',9.81, ...
    'referenceTemperature_C',20,'freezeEnabled',false, ...
    'viscosityEnabled',false,'bulkFreezingTemperature_C',0, ...
    'wallEnergyDifference_J_m2',0,'iceDensity_kg_m3',917, ...
    'latentHeat_J_kg',3.35e5,'meltingTemperature_K',273.15, ...
    'transitionWidth_C',0,'sampleWeights',[], ...
    'baseMobilityFactor',1,'baseMobilityDerivative_dT',[]);
names=fieldnames(options);
assert(all(ismember(names,fieldnames(s))),'JointOpeningHydraulics:Options', ...
    'Unknown opening-hydraulics option.');
for k=1:numel(names), s.(names{k})=options.(names{k}); end
assert(isnumeric(Cref)&&isreal(Cref)&&isvector(Cref)&& ...
    all(isfinite(Cref(:)))&&all(Cref(:)>=0), ...
    'JointOpeningHydraulics:Conductance','Cref must be a finite nonnegative vector.');
assert(isnumeric(gap)&&isreal(gap)&&isvector(gap)&&all(isfinite(gap(:))), ...
    'JointOpeningHydraulics:Gap','gap must be a finite signed-opening vector.');
nj=max(numel(Cref),numel(gap));
Cref=jointValue(Cref,nj,'Cref',0,Inf); gap=jointValue(gap,nj,'gap',-Inf,Inf);
fraction=jointValue(s.openingTransmissionFraction,nj,'openingTransmissionFraction',0,1);
length=jointValue(s.pathLength_m,nj,'pathLength_m',realmin,Inf);
baseFactor=jointValue(s.baseMobilityFactor,nj,'baseMobilityFactor',0,Inf);
assert(isnumeric(Tprofile)&&isreal(Tprofile)&&ismatrix(Tprofile)&& ...
    all(isfinite(Tprofile(:)))&&(isempty(Tprofile)||size(Tprofile,1)==nj), ...
    'JointOpeningHydraulics:Temperature', ...
    'Tprofile must have one row per joint and finite path temperatures.');
if isempty(Tprofile), Tprofile=zeros(nj,0); end
Tprofile=double(Tprofile); nq=size(Tprofile,2);
switchNames={'freezeEnabled','viscosityEnabled'};
for k=1:numel(switchNames)
    value=s.(switchNames{k});
    assert(isscalar(value)&&isreal(value)&&isfinite(value)&&ismember(value,[0 1]), ...
        'JointOpeningHydraulics:Switch','Switches must be scalar logical 0/1.');
end
assert(nq>0||(~s.freezeEnabled&&~s.viscosityEnabled), ...
    'JointOpeningHydraulics:MissingTemperature', ...
    'Enabled slit freezing or viscosity requires path temperatures.');
positiveNames={'waterDensity_kg_m3','gravity_m_s2','iceDensity_kg_m3', ...
    'latentHeat_J_kg','meltingTemperature_K'};
for k=1:numel(positiveNames)
    value=s.(positiveNames{k});
    assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value)&&value>0, ...
        'JointOpeningHydraulics:Constant','Physical constants must be positive scalars.');
end
assert(isnumeric(s.wallEnergyDifference_J_m2)&&isreal(s.wallEnergyDifference_J_m2) ...
    &&isscalar(s.wallEnergyDifference_J_m2)&&isfinite(s.wallEnergyDifference_J_m2) ...
    &&s.wallEnergyDifference_J_m2>=0&&isnumeric(s.transitionWidth_C) ...
    &&isreal(s.transitionWidth_C)&&isscalar(s.transitionWidth_C) ...
    &&isfinite(s.transitionWidth_C)&&s.transitionWidth_C>=0, ...
    'JointOpeningHydraulics:FreezeParameter', ...
    'Wall-energy difference and numerical transition width must be nonnegative scalars.');
assert(isnumeric(s.bulkFreezingTemperature_C)&&isreal(s.bulkFreezingTemperature_C) ...
    &&isscalar(s.bulkFreezingTemperature_C)&&isfinite(s.bulkFreezingTemperature_C), ...
    'JointOpeningHydraulics:FreezeParameter','Bulk freezing temperature must be finite.');
assert(isnumeric(s.referenceTemperature_C)&&isreal(s.referenceTemperature_C) ...
    &&isscalar(s.referenceTemperature_C)&&isfinite(s.referenceTemperature_C), ...
    'JointOpeningHydraulics:ReferenceTemperature','Reference temperature must be finite and scalar.');
muRef=waterViscosity(s.referenceTemperature_C);
coefficient=s.waterDensity_kg_m3*s.gravity_m_s2./(12*muRef*length);
defect=Cref>0; b=fraction.*max(gap,0).*defect;
dbdg=fraction.*(gap>0).*defect;
CopenReference=coefficient.*b.^3;
baseAperture=(Cref./coefficient).^(1/3);
factor=ones(nj,1); dFactorB=zeros(nj,1); dFactorT=zeros(nj,nq);
Tf=s.bulkFreezingTemperature_C*ones(nj,1); dTfB=zeros(nj,1);
phase=ones(nj,nq); dPhaseT=zeros(nj,nq);
beta=2*s.meltingTemperature_K*s.wallEnergyDifference_J_m2 ...
    /(s.iceDensity_kg_m3*s.latentHeat_J_kg);
open=b>0;
if beta>0
    Tf(open)=s.bulkFreezingTemperature_C-beta./b(open);
    dTfB(open)=beta./b(open).^2;
end
if s.freezeEnabled
    excess=Tprofile-Tf;
    if s.transitionWidth_C==0
        phase=double(excess>=0);
    else
        u=excess/s.transitionWidth_C+.5;
        phase=double(u>=1); middle=u>0&u<1;
        phase(middle)=u(middle).^2.*(3-2*u(middle));
        dPhaseT(middle)=6*u(middle).*(1-u(middle))/s.transitionWidth_C;
    end
end
muRatio=ones(nj,nq); dMuRatioT=zeros(nj,nq);
if s.viscosityEnabled
    [mu,dMu]=waterViscosity(Tprofile);
    muRatio=mu/muRef; dMuRatioT=dMu/muRef;
end
if nq>0
    weights=s.sampleWeights;
    if isempty(weights), weights=ones(1,nq)/nq; end
    assert(isnumeric(weights)&&isreal(weights)&&isvector(weights)&&numel(weights)==nq ...
        &&all(isfinite(weights(:)))&&all(weights(:)>0), ...
        'JointOpeningHydraulics:Weights','sampleWeights must be positive path-length fractions.');
    weights=double(weights(:)'); weights=weights/sum(weights);
    active=all(phase>0,2)&open;
    factor(~active)=0;
    if any(active)
        phi=phase(active,:); mr=muRatio(active,:);
        resistance=mr./phi;
        factor(active)=1./sum(weights.*resistance,2);
        dResistanceT=dMuRatioT(active,:)./phi-mr.*dPhaseT(active,:)./phi.^2;
        dFactorT(active,:)=-factor(active).^2.*weights.*dResistanceT;
        dPhaseB=-dPhaseT(active,:).*dTfB(active);
        dFactorB(active)=factor(active).^2.*sum(weights.*mr.*dPhaseB./phi.^2,2);
    end
else
    weights=zeros(1,0);
end
Copen=CopenReference.*factor;
dCdg=(3*coefficient.*b.^2.*factor+CopenReference.*dFactorB).*dbdg;
baseDerivative=s.baseMobilityDerivative_dT;
if isempty(baseDerivative), baseDerivative=zeros(nj,nq); end
assert(isnumeric(baseDerivative)&&isreal(baseDerivative) ...
    &&isequal(size(baseDerivative),[nj nq])&&all(isfinite(baseDerivative(:))), ...
    'JointOpeningHydraulics:BaseDerivative','Base derivative must be nj-by-nq.');
C=Cref.*baseFactor+Copen;
dCdT=Cref.*double(baseDerivative)+CopenReference.*dFactorT;
volume=length.*b; dVolumeG=length.*dbdg;
sampleVolume=volume.*weights;
dPhaseB=-dPhaseT.*dTfB;
liquidVolume=sampleVolume.*phase; iceVolume=sampleVolume.*(1-phase);
dLiquidVolumeG=(dVolumeG.*weights).*phase ...
    +sampleVolume.*dPhaseB.*dbdg;
dIceVolumeG=dVolumeG.*weights-dLiquidVolumeG;
dLiquidVolumeT=sampleVolume.*dPhaseT;
status=repmat({'closed_or_disabled'},nj,1); status(~defect)={'sealed'};
status(open)={'open_slit'}; status(open&factor==0)={'open_slit_ice_blocked'};
diagnostic=struct('baseAperture',baseAperture, ...
    'openingContribution',b,'aperture_m',b,'conductance',C, ...
    'baseConductance',Cref.*baseFactor,'openConductance',Copen, ...
    'referenceOpenConductance',CopenReference,'openMobilityFactor',factor, ...
    'freezeTemperature_C',Tf,'conductingFractionBySample',phase, ...
    'liquidFractionBySample',phase,'dLiquidFraction_dTemperature',dPhaseT, ...
    'dLiquidFraction_dGap',dPhaseB.*dbdg, ...
    'newslitGeometricVolume_m2',volume,'newslitWaterVolume_m2',volume, ...
    'dVolume_dGap_m',dVolumeG,'sampleVolume_m2',sampleVolume, ...
    'liquidVolumeBySample_m2',liquidVolume,'iceVolumeBySample_m2',iceVolume, ...
    'dLiquidVolume_dGap_m',dLiquidVolumeG,'dIceVolume_dGap_m',dIceVolumeG, ...
    'dLiquidVolume_dTemperature_m2_K',dLiquidVolumeT, ...
    'dIceVolume_dTemperature_m2_K',-dLiquidVolumeT, ...
    'localMobility',phase./muRatio,'sealedMask',~defect,'status',{status}, ...
    'sampleWeights',weights,'settings',s, ...
    'baseApertureInterpretation', ...
    'Equivalent warm parallel-plate aperture only; not a capillary radius and never added to the new slit.', ...
    'assumptions',{{ ...
    'New connected smooth slit is parallel to the unchanged pre-existing defect network.', ...
    'Unit axial width; incompressible laminar flow; uniform hydraulic aperture and prescribed path length.', ...
    'Opening transmission fraction and wall-energy difference need independent calibration.', ...
    'No new leak is created at Cref=0; no gasket failure or irreversible damage law.', ...
    'Slit equilibrium uses wall energy difference; default zero denotes bulk freezing.', ...
    'Nonzero transitionWidth_C is numerical regularization, not a measured SFCC or premelting film.', ...
    'Returned geometric liquid/ice volumes require separate water and latent/sensible heat inventories in the caller.', ...
    'newslitWaterVolume_m2 is water-equivalent geometric volume under an equal-density inventory approximation, not physical mass.', ...
    'Closing the slit can reverse inlet flow; pressure/storage closure and the correct heat donor are caller responsibilities.', ...
    'No moving-channel storage residual, latent heat equation, mechanical work or fracture-energy equation is supplied by this kernel.'}}, ...
    'hydraulicLawDOI','10.1029/WR016i006p01016', ...
    'slitThermodynamicsDOI','10.1063/5.0044330');
end

function value=jointValue(value,nj,name,minimum,maximum)
assert(isnumeric(value)&&isreal(value)&&isvector(value)&&all(isfinite(value(:))) ...
    &&all(value(:)>=minimum)&&all(value(:)<=maximum) ...
    &&(isscalar(value)||numel(value)==nj), ...
    'JointOpeningHydraulics:JointParameter','Invalid %s value/inventory.',name);
value=double(value(:)); if isscalar(value), value=repmat(value,nj,1); end
end

function [mu,dMu]=waterViscosity(T)
% Same ambient-pressure IAPWS four-term law used by joint_freeze_conductance.
assert(isnumeric(T)&&isreal(T)&&all(isfinite(T(:)))&&all(T(:)>=-20&T(:)<=110), ...
    'JointOpeningHydraulics:ViscosityTemperature', ...
    'Water-viscosity temperatures must lie between -20 and 110 C.');
tau=(double(T)+273.15)/300;
coefficients=[280.68,511.45,61.131,.45903]; exponents=[-1.9,-7.7,-19.6,-40];
mu=zeros(size(T)); dMu=zeros(size(T));
for k=1:4
    mu=mu+1e-6*coefficients(k)*tau.^exponents(k);
    dMu=dMu+(1e-6*coefficients(k)*exponents(k)/300)*tau.^(exponents(k)-1);
end
end
