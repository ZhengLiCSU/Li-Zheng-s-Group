function result=run_TH_segment_year20_thm(user)
%RUN_TH_SEGMENT_YEAR20_THM Complete annual THM history with installed reference.
% Default: 20 consecutive 365-day years using TH_2D_segment_v16 and the
% illustrative eight-joint supply model. This driver never resets the
% mechanical reference or uses a converged-cycle shortcut. Every next year
% starts from the PREVIOUS COMPLETE v16 checkpoint, including displacement,
% installed reference U/T and full coupled state. Parameter cases require
% independent folders; v14/v15 annual or core checkpoints are rejected.
%
% r=run_TH_segment_year20_thm;
% r=run_TH_segment_year20_thm(struct('resume',true));
% user: model (nested overrides), maxYears (1..20), resume, outputFolder.
% maxYears<20 is for verification; year-20 response remains NaN. A marker
% PAUSE_AFTER_YEAR pauses after committing a complete year. Remove it and
% resume with exactly the same model and maxYears. Schema11 can restore the
% complete accepted-history inventory from a monthly/failed checkpoint;
% the original year-start full state and installed reference are retained.
% The driver preserves the v16 physical scope; it does not add gasket
% calibration, damage, new slit storage or omitted-work terms to that core.

if nargin<1, user=struct(); end
assert(isstruct(user)&&isscalar(user),'THMAnnual:Config','user must be a scalar struct.');
root=fileparts(mfilename('fullpath')); addpath(root);
c=struct('maxYears',20,'resume',false, ...
    'outputFolder',fullfile(root,'segment_year20_thm_v16_illustrative'),'model',struct());
names=fieldnames(user);
for k=1:numel(names)
    assert(isfield(c,names{k}),'THMAnnual:Config','Unknown driver option: %s.',names{k});
    c.(names{k})=user.(names{k});
end
assert(isnumeric(c.maxYears)&&isscalar(c.maxYears)&&isfinite(c.maxYears) ...
    &&c.maxYears==fix(c.maxYears)&&c.maxYears>=1&&c.maxYears<=20, ...
    'THMAnnual:Config','maxYears must be an integer from 1 to 20.');
assert(isscalar(c.resume)&&isreal(c.resume)&&isfinite(c.resume)&&ismember(c.resume,[0 1]), ...
    'THMAnnual:Config','resume must be scalar logical 0/1.');
assert(isstruct(c.model)&&isscalar(c.model),'THMAnnual:Config','model must be a scalar struct.');
assert((ischar(c.outputFolder)&&isrow(c.outputFolder)) ...
    ||(isstring(c.outputFolder)&&isscalar(c.outputFolder)), ...
    'THMAnnual:Config','outputFolder must be a path string.');
c.outputFolder=char(c.outputFolder);
assert(~isempty(c.outputFolder),'THMAnnual:Config','outputFolder cannot be empty.');
% Canonical absolute paths keep all checkpoint links unambiguous on resume.
folderObject=java.io.File(c.outputFolder);
c.outputFolder=char(folderObject.getCanonicalPath());
base=struct('durationDays',365,'outputEveryDays',365/12, ...
    'plot',false,'verbose',false,'saveOutput',true, ...
    'dtInitial',.1*86400,'dtMax',86400,'dtMin',86400/16384, ...
    'initial',struct('mode','profile','startDay',0), ...
    'thm',struct('enabled',true),'mechanics',struct('enable',false), ...
    'solver',struct('fd',1e-8,'maxIter',60,'tol',2e-8));
model=joint_supply_th_model(combine(base,c.model));
assert(model.thm.enabled,'THMAnnual:Model','This driver requires enabled two-way THM.');
assert(any(strcmp(model.initial.mode,{'profile','fields'})), ...
    'THMAnnual:Initial','Fresh histories require profile or supplied fields, not an external checkpoint.');
assert(~isfield(model.initial,'startDay')||model.initial.startDay==0, ...
    'THMAnnual:Initial','The 20-year history must begin at day zero.');
assert(~isfield(model,'yearDays')||model.yearDays==365, ...
    'THMAnnual:Model','This driver uses repeated 365-day years.');
assert(~isfield(model,'day')||model.day==86400, ...
    'THMAnnual:Model','This driver requires day=86400 s.');
assert(model.dtMax>0&&model.dtMax<=4*86400, ...
    'THMAnnual:Model','Maximum step must be positive and at most four days.');
model.durationDays=365; model.outputEveryDays=365/12;
model.plot=false; model.saveOutput=true; model.initial.startDay=0;
if isfield(model,'outputPrefix'), model=rmfield(model,'outputPrefix'); end
c.model=model;
if ~isfolder(c.outputFolder), mkdir(c.outputFolder); end
rejectLegacyFolder(c.outputFolder);
progressFile=fullfile(c.outputFolder,'thm_progress.mat');
annualColumns={'year','totalLeak_m3_per_m','jointLeak_m3_per_m','bodyLeak_m3_per_m', ...
    'waterDefect_m3_per_m','energyDefect_J_per_m','maxAbsWaterDefect_m3_per_m', ...
    'maxAbsEnergyDefect_J_per_m','acceptedSteps','maxScaledResidual', ...
    'maxAbsVolumetricStrain','maxJointGap_m','maxFreeMechanicalResidual_N_per_m', ...
    'maxOmittedNewSlitVolumeFraction'};
nj=numel(model.leakage.jointAnglesRad);
monthlyColumns=[{'year','month','totalLeak_m3_per_m'},jointHeaders(nj)];
jointColumns={'year','jointID','angle_rad','leak_m3_per_m'};
dailyColumns=[{'year','dayOfYear','absoluteEndDay','totalLeak_m3_per_m'},jointHeaders(nj)];
restartNote='Incomplete years restore the complete accepted-step inventory at the latest compatible checkpoint; full X and installed reference are preserved.';
if c.resume
    assert(isfile(progressFile),'THMAnnual:MissingProgress','No v16 THM annual progress exists.');
    saved=load(progressFile,'progress'); progress=saved.progress;
    assert(isfield(progress,'schemaVersion')&&progress.schemaVersion==11 ...
        &&strcmp(progress.engineVersion,'THM_v16_20260930_analytic_p1'), ...
        'THMAnnual:Schema','A dedicated schema-11 v16 THM progress file is required.');
    assert(isequaln(rmfield(c,{'resume','outputFolder'}), ...
        rmfield(progress.config,{'resume','outputFolder'})), ...
        'THMAnnual:ResumeConfig','Resume requires identical model and year limit.');
    assert(progress.completedYears>=0&&progress.completedYears<=c.maxYears ...
        &&progress.completedYears==fix(progress.completedYears), ...
        'THMAnnual:Progress','Invalid completed-year inventory.');
else
    assert(~isfile(progressFile),'THMAnnual:OutputExists', ...
        'Output already exists. Use resume=true or a new outputFolder.');
    assert(isempty(dir(fullfile(c.outputFolder,'year_*_checkpoint.mat'))), ...
        'THMAnnual:OrphanCheckpoint','Unregistered year checkpoints require a new output folder.');
    progress=struct('schemaVersion',11,'engineVersion','THM_v16_20260930_analytic_p1', ...
        'config',c,'completedYears',0,'lastYear',[],'coreCheckpoints',{{}}, ...
        'installedMechanicalReference',[],'annual',zeros(0,numel(annualColumns)), ...
        'monthly',zeros(0,numel(monthlyColumns)),'byJoint',zeros(0,4), ...
        'daily',zeros(0,numel(dailyColumns)), ...
        'annualColumns',{annualColumns},'monthlyColumns',{monthlyColumns}, ...
        'jointColumns',{jointColumns},'dailyColumns',{dailyColumns}, ...
        'restartNote',restartNote);
    saveProgress(progress,progressFile);
end
started=tic; status='completed_requested_years'; numericalFailure='';
for year=progress.completedYears+1:c.maxYears
    o=model; prefix=fullfile(c.outputFolder,sprintf('year_%02d',year));
    o.outputPrefix=prefix;
    if year==1
        o.initial.startDay=0;
    else
        priorFile=progress.coreCheckpoints{year-1};
        prior=checkedCheckpoint(priorFile,(year-1)*365);
        assert(isequal(prior.mechanicalReference,progress.installedMechanicalReference), ...
            'THMAnnual:Reference','Prior checkpoint changed the installed mechanical reference.');
        o.initial=struct('mode','checkpoint','checkpointFile',priorFile);
    end
    partialUsed=false; recovered=[]; selectedTime=(year-1)*365;
    for suffix={'_checkpoint.mat','_FAILED_checkpoint.mat'}
        file=[prefix suffix{1}];
        if ~isfile(file), continue; end
        try
            candidate=load(file,'checkpoint');
        catch ME
            warning('THMAnnual:UnreadableCheckpoint', ...
                'Preserving unreadable checkpoint %s; another complete checkpoint will be used: %s',file,ME.message);
            continue
        end
        cpCandidate=candidate.checkpoint;
        assert(strcmp(cpCandidate.version,progress.engineVersion), ...
            'THMAnnual:Engine','Incomplete checkpoint belongs to a different physical implementation.');
        cpDay=cpCandidate.time/86400;
        assert(cpDay>=(year-1)*365&&cpDay<=year*365+1e-7,'THMAnnual:History','Checkpoint is outside its year.');
        if abs(cpDay-year*365)<1e-7
            assert(isfield(cpCandidate,'runInventory'),'THMAnnual:CompletedInventory', ...
                'A complete checkpoint needs its accepted-history inventory for result reconstruction.');
            if isfile([prefix '_results.mat'])
                core=load([prefix '_results.mat'],'out'); recovered=core.out;
                validateRecoveredResult(recovered,cpCandidate,model);
            end
            % The core validates the current FULL physical signature and mesh,
            % then restores the original complete history and only finalizes
            % diagnostics/output. No additional time step is allowed here.
            o.initial=struct('mode','checkpoint','checkpointFile',file,'resumeHistory',true);
            selectedTime=cpDay;
        elseif cpDay>selectedTime && isfield(cpCandidate,'runInventory')
            if year>1
                assert(isequal(cpCandidate.mechanicalReference,progress.installedMechanicalReference), ...
                    'THMAnnual:Reference','Partial checkpoint changed installed reference.');
                assert(isequal(cpCandidate.runInventory.startX,prior.X), ...
                    'THMAnnual:State','Partial history has a different preceding full state.');
            end
            o.initial=struct('mode','checkpoint','checkpointFile',file,'resumeHistory',true);
            partialUsed=true; selectedTime=cpDay;
        end
    end
    fprintf('Starting coupled THM year %d/%d; installed reference preserved across years.\n',year,c.maxYears);
    try
        out=TH_2D_segment_v16(o);
        if ~isempty(recovered)
            assert(isequal(out.finalX,recovered.finalX) ...
                &&isequal(out.initialX,recovered.initialX) ...
                &&isequal(out.history,recovered.history), ...
                'THMAnnual:RecoveredHistory', ...
                'Finalizing a complete checkpoint must retain the archived full state and every accepted step.');
        end
    catch ME
        if ~strcmp(ME.identifier,'TH:nonconvergence'), rethrow(ME); end
        numericalFailure=sprintf('Year %d stopped with accepted-state checkpoints retained: %s',year,ME.message);
        status='numerical_failure_saved'; warning('THMAnnual:Failure','%s',numericalFailure); break
    end
    assert(strcmp(out.version,progress.engineVersion)&&isfield(out,'finalX'), ...
        'THMAnnual:Engine','The v16 THM engine with finalX is required.');
    assert(abs(out.timeDay-year*365)<1e-7&&~isempty(out.history) ...
        &&all(isfinite(out.history(:)))&&all(diff(out.history(:,1))>0) ...
        &&abs(sum(out.history(:,2))-365)<1e-6 ...
        &&abs(out.history(1,1)-out.history(1,2)-(year-1)*365)<1e-7, ...
        'THMAnnual:History','A complete, unique 365-day accepted-step history is required.');
    assert(isfield(out,'mechanics')&&size(out.mechanics.history,1)==size(out.history,1), ...
        'THMAnnual:MechanicalHistory','Mechanical history must cover every accepted THM step.');
    cpFile=[prefix '_checkpoint.mat']; cp=checkedCheckpoint(cpFile,year*365);
    assert(isequal(cp.X,out.finalX),'THMAnnual:State','Year-end checkpoint differs from final coupled state.');
    assert(isequal(cp.mechanicalReference.U,out.mechanics.referenceU) ...
        &&isequal(cp.mechanicalReference.T,out.mechanics.referenceTemperature), ...
        'THMAnnual:Reference','Core output and checkpoint mechanical references differ.');
    if year==1
        progress.installedMechanicalReference=cp.mechanicalReference;
    else
        assert(isequal(cp.mechanicalReference,progress.installedMechanicalReference), ...
            'THMAnnual:Reference','Installed U/T reference must remain EXACTLY unchanged across years.');
        assert(isequal(out.initialX,prior.X),'THMAnnual:State', ...
            'A new year must inherit the entire prior coupled checkpoint state.');
    end
    leak=out.leakage; h=out.history; mh=out.mechanics.history;
    total=leak.totalVolume_m3_per_m; joint=sum(leak.volumeByJoint_m3_per_m);
    assert(numel(leak.dailyTotalVolume_m3_per_m)==365 ...
        &&numel(leak.monthlyTotalVolume_m3_per_m)==12 ...
        &&abs(total-sum(leak.dailyTotalVolume_m3_per_m))<1e-8 ...
        &&abs(total-sum(leak.monthlyTotalVolume_m3_per_m))<1e-8 ...
        &&abs(total-joint-leak.bodyVolume_m3_per_m)<1e-8, ...
        'THMAnnual:LeakPartition','Annual, daily, monthly and joint volumes must agree.');
    progress.annual(end+1,:)=[year total joint leak.bodyVolume_m3_per_m ...
        sum(h(:,8)) sum(h(:,9)) max(abs(h(:,8))) max(abs(h(:,9))) ...
        size(h,1) max(h(:,11)) max(mh(:,2)) max(mh(:,3)) max(mh(:,5)) max(mh(:,6))];
    progress.monthly=[progress.monthly;year*ones(12,1),(1:12)', ...
        leak.monthlyTotalVolume_m3_per_m,leak.monthlyVolumeByJoint_m3_per_m]; %#ok<AGROW>
    progress.byJoint=[progress.byJoint;year*ones(nj,1),(1:nj)', ...
        model.leakage.jointAnglesRad(:),leak.volumeByJoint_m3_per_m(:)]; %#ok<AGROW>
    progress.daily=[progress.daily;year*ones(365,1),(1:365)', ...
        leak.dailyBinEndDay,leak.dailyTotalVolume_m3_per_m, ...
        leak.dailyVolumeByJoint_m3_per_m]; %#ok<AGROW>
    out.annualContinuation=struct('schemaVersion',11,'year',year, ...
        'partialYearResumeUsed',partialUsed,'installedReferencePreserved',true, ...
        'coreCheckpoint',cpFile,'restartNote',restartNote);
    strainTable=array2table([year*ones(size(out.mechanics.strainHistory,1),1), ...
        out.mechanics.strainHistory], ...
        'VariableNames',[{'year'},out.mechanics.strainHistoryColumns]);
    writetable(strainTable,[prefix '_strain_history.csv']);
    progress.lastYear=out; progress.completedYears=year;
    progress.coreCheckpoints{year}=cpFile;
    save([prefix '_annual_results.mat'],'out','-v7');
    % A committed year must already have its complete raw annual archive.
    saveProgress(progress,progressFile);
    writeTables(progress,c.outputFolder);
    fprintf('THM year %d complete: %.6g L/m, %d steps, max strain %.3g, max gap %.3g m.\n', ...
        year,1000*total,size(h,1),max(mh(:,2)),max(mh(:,3)));
    if year<c.maxYears&&isfile(fullfile(c.outputFolder,'PAUSE_AFTER_YEAR'))
        status='paused_at_year_boundary'; break
    end
end
result=struct('schemaVersion',11,'engineVersion',progress.engineVersion, ...
    'status',status,'completedYears',progress.completedYears,'config',c, ...
    'lastYear',progress.lastYear,'coreCheckpoints',{progress.coreCheckpoints}, ...
    'installedMechanicalReference',progress.installedMechanicalReference, ...
    'annual',progress.annual,'annualColumns',{progress.annualColumns}, ...
    'monthly',progress.monthly,'monthlyColumns',{progress.monthlyColumns}, ...
    'byJoint',progress.byJoint,'jointColumns',{progress.jointColumns}, ...
    'daily',progress.daily,'dailyColumns',{progress.dailyColumns}, ...
    'elapsedWallTime_s',toc(started),'numericalFailure',numericalFailure, ...
    'restartNote',restartNote,'partialYearResumeSupported',true, ...
    'year20AnnualLeakage_L_per_m',NaN,'year20ByJoint_L_per_m',NaN, ...
    'year20JointLeakage_L_per_m',NaN,'year20BodyLeakage_L_per_m',NaN, ...
    'year20ByMonth_L_per_m',NaN,'year20MonthlyByJoint_L_per_m',NaN, ...
    'year20DailyLeakage_L_per_day_per_m',NaN);
if progress.completedYears==20
    leak=progress.lastYear.leakage;
    result.year20AnnualLeakage_L_per_m=1000*leak.totalVolume_m3_per_m;
    result.year20JointLeakage_L_per_m=1000*sum(leak.volumeByJoint_m3_per_m);
    result.year20BodyLeakage_L_per_m=1000*leak.bodyVolume_m3_per_m;
    result.year20ByJoint_L_per_m=1000*leak.volumeByJoint_m3_per_m;
    result.year20ByMonth_L_per_m=1000*leak.monthlyTotalVolume_m3_per_m;
    result.year20MonthlyByJoint_L_per_m=1000*leak.monthlyVolumeByJoint_m3_per_m;
    result.year20DailyLeakage_L_per_day_per_m=1000*leak.dailyTotalVolume_m3_per_m;
end
writeTables(progress,c.outputFolder);
save(fullfile(c.outputFolder,'TH_segment_year20_thm_results.mat'),'result','-v7');
end

function cp=checkedCheckpoint(file,day)
assert(isfile(file),'THMAnnual:MissingCheckpoint','Missing completed-year core checkpoint: %s.',file);
d=load(file,'checkpoint'); cp=d.checkpoint;
assert(strcmp(cp.version,'THM_v16_20260930_analytic_p1') ...
    &&isfield(cp,'mechanicalReference')&&all(isfinite(cp.X)) ...
    &&abs(cp.time/86400-day)<1e-7,'THMAnnual:Checkpoint', ...
    'A complete, compatible v16 THM checkpoint with mechanical reference is required.');
end

function validateRecoveredResult(out,cp,model)
% Validate the stored archive before it can be replaced by zero-step core
% finalization. The subsequent public core call additionally checks its full
% checkpoint signature against CURRENT defaults/overrides and every canonical
% geometry field, so this path cannot bypass the core's continuation checks.
required={'version','parameters','mesh','pAll','soilNodes','initialX','finalX','history'};
assert(isstruct(out)&&isscalar(out)&&all(isfield(out,required)) ...
    &&strcmp(out.version,cp.version),'THMAnnual:RecoveredArchive', ...
    'The completed result archive is missing compatible full-state metadata.');
assert(isequaln(physicalSignature(out.parameters),cp.signature), ...
    'THMAnnual:RecoveredPhysicalConfig', ...
    'Completed result physical parameters differ from its checkpoint.');
if isfield(model,'mesh')&&~isempty(model.mesh)
    expectedMesh=model.mesh;
else
    assert(isfield(model,'meshFile')&&isfile(model.meshFile), ...
        'THMAnnual:RecoveredMesh','The configured mesh is unavailable.');
    expectedMesh=load(model.meshFile);
end
assert(isequaln(out.mesh,expectedMesh) ...
    &&isequal(out.pAll,cp.pAll)&&isequal(out.pAll,expectedMesh.pAll) ...
    &&isequal(out.soilNodes,cp.soilNodes) ...
    &&isequal(out.soilNodes,unique(expectedMesh.tSoil(:))) ...
    &&isequal(cp.tSoil,expectedMesh.tSoil), ...
    'THMAnnual:RecoveredMesh', ...
    'Completed result, checkpoint and current configured mesh differ.');
assert(isfield(cp,'runInventory') ...
    &&isequal(out.initialX,cp.runInventory.startX)&&isequal(out.finalX,cp.X), ...
    'THMAnnual:RecoveredState', ...
    'Completed result has a different original start or final coupled state.');
end

function s=physicalSignature(p)
% Keep annual recovery and core continuation under the same closure guard.
s=thm_constitutive_signature(p);
end

function rejectLegacyFolder(folder)
legacy={'spinup_progress.mat','TH_segment_spinup_results.mat','active_year_checkpoint.mat'};
for k=1:numel(legacy)
    assert(~isfile(fullfile(folder,legacy{k})),'THMAnnual:LegacyFolder', ...
        'Use a dedicated THM folder; a previous TH runner artifact was found.');
end
files=dir(fullfile(folder,'*_checkpoint.mat'));
for k=1:numel(files)
    file=fullfile(folder,files(k).name);
    try
        names=whos('-file',file);
    catch ME
        warning('THMAnnual:UnreadableCheckpoint', ...
            'Preserving unreadable checkpoint %s; compatible registered or alternate checkpoints remain eligible: %s', ...
            file,ME.message);
        continue
    end
    assert(ismember('checkpoint',{names.name}),'THMAnnual:LegacyFolder', ...
        'A checkpoint without a registered v16 THM state was found in this folder.');
    try
        saved=load(file,'checkpoint');
    catch ME
        warning('THMAnnual:UnreadableCheckpoint', ...
            'Preserving unreadable checkpoint %s; compatible registered or alternate checkpoints remain eligible: %s', ...
            file,ME.message);
        continue
    end
    cp=saved.checkpoint;
    assert(isstruct(cp)&&isscalar(cp)&&isfield(cp,'version') ...
        &&strcmp(cp.version,'THM_v16_20260930_analytic_p1'), ...
        'THMAnnual:LegacyFolder','A v14/v15 or incompatible core checkpoint was found. Use a dedicated THM folder.');
end
end

function saveProgress(progress,file)
temporary=[file '.tmp.mat']; save(temporary,'progress','-v7');
[ok,message]=movefile(temporary,file,'f');
assert(ok,'THMAnnual:ProgressWrite','Cannot commit complete-year progress: %s.',message);
end

function writeTables(progress,folder)
writetable(array2table(progress.annual,'VariableNames',progress.annualColumns), ...
    fullfile(folder,'thm_annual_leakage.csv'));
writetable(array2table(progress.monthly,'VariableNames',progress.monthlyColumns), ...
    fullfile(folder,'thm_monthly_leakage.csv'));
writetable(array2table(progress.byJoint,'VariableNames',progress.jointColumns), ...
    fullfile(folder,'thm_joint_annual_leakage.csv'));
writetable(array2table(progress.daily,'VariableNames',progress.dailyColumns), ...
    fullfile(folder,'thm_daily_leakage.csv'));
end

function names=jointHeaders(nj)
names=cell(1,nj);
for k=1:nj, names{k}=sprintf('joint%dLeak_m3_per_m',k); end
end

function a=combine(a,b)
names=fieldnames(b);
for k=1:numel(names)
    name=names{k};
    if isfield(a,name)&&isstruct(a.(name))&&isstruct(b.(name)) ...
            &&isscalar(a.(name))&&isscalar(b.(name))
        a.(name)=combine(a.(name),b.(name));
    else
        a.(name)=b.(name);
    end
end
end
