function comparison=benchmark_joint_only_year20_dt1(outputFolder)
%BENCHMARK_JOINT_ONLY_YEAR20_DT1 Re-run age 20 from the SAME year-19 state.
% This isolates year-20 time integration error; it does not replace a
% complete 20-year 1-day reference or a mesh convergence study.
root=fileparts(mfilename('fullpath'));
if nargin<1 || isempty(outputFolder)
    outputFolder=fullfile(root,'segment_year20_jointonly_8segment_illustrative');
end
s=load(fullfile(outputFolder,'TH_segment_spinup_results.mat'),'result');
r=s.result;
assert(r.completedYears==20 && r.lastYear.parameters.liningK==0);
fast=r.lastYear;
o=fast.parameters;
n=numel(fast.T);
o.mesh=fast.mesh;
o.initial=struct('mode','fields','T',fast.initialX(1:n), ...
    'h',fast.initialX(n+1:end),'startDay',19*365);
o.durationDays=365; o.outputEveryDays=365/12;
o.dtInitial=.1*86400; o.dtMax=86400; o.dtMin=86400/16384;
o.plot=false; o.verbose=false; o.saveOutput=false;
started=tic;
ref=TH_2D_segment_jointonly(o);
elapsed_s=toc(started);
qFast=1000*fast.leakage.totalVolume_m3_per_m;
qRef=1000*ref.leakage.totalVolume_m3_per_m;
comparison=struct('fast4_L_per_m',qFast,'oneDay_L_per_m',qRef, ...
    'absoluteDifference_L_per_m',abs(qFast-qRef), ...
    'relativeDifference_percent',100*abs(qFast-qRef)/max(qRef,eps), ...
    'maximumMonthlyDifference_L_per_m',1000*max(abs( ...
        fast.leakage.monthlyTotalVolume_m3_per_m(:)- ...
        ref.leakage.monthlyTotalVolume_m3_per_m(:))), ...
    'maximumJointAnnualDifference_L_per_m',1000*max(abs( ...
        fast.leakage.volumeByJoint_m3_per_m(:)- ...
        ref.leakage.volumeByJoint_m3_per_m(:))), ...
    'dailyTotalL1Difference_L_per_m',1000*sum(abs( ...
        fast.leakage.dailyTotalVolume_m3_per_m(:)- ...
        ref.leakage.dailyTotalVolume_m3_per_m(:))), ...
    'referenceElapsed_s',elapsed_s, ...
    'referenceMinStepDays',min(ref.history(:,2)), ...
    'referenceRejectedSteps',ref.solverWork.rejectedSteps, ...
    'referenceMaxWaterDefect_m2',max(abs(ref.history(:,8))), ...
    'referenceMaxEnergyDefect_J_per_m',max(abs(ref.history(:,9))));
assert(ref.leakage.bodyVolume_m3_per_m==0 && ...
    abs(sum(ref.leakage.volumeByJoint_m3_per_m)- ...
        ref.leakage.totalVolume_m3_per_m)<1e-9);
save(fullfile(outputFolder,'joint_only_year20_dt1_comparison.mat'), ...
    'comparison','-v7');
disp(comparison);
end
