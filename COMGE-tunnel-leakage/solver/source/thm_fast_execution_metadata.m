function execution=thm_fast_execution_metadata(out,threads,priorThreads,elapsed)
%THM_FAST_EXECUTION_METADATA Record the actual resolved fast discretization.
% Custom meshes and nested overrides must not inherit a default preset label.
p=out.parameters;
execution=struct('numThreads',threads,'restoredThreadsAfterReturn',priorThreads, ...
    'numericalPreset','resolved_consecutive_THM', ...
    'meshFile',p.meshFile, ...
    'thermalNodes',numel(out.T),'soilNodes',numel(out.h), ...
    'totalUnknowns',numel(out.finalX),'soilTriangles',size(out.mesh.tSoil,1), ...
    'phaseQuadratureOrder',out.numerics.phaseQuadratureOrder, ...
    'phaseQuadraturePoints',out.numerics.phaseQuadraturePoints, ...
    'dtMax_days',p.dtMax/86400,'resolvedSolver',p.solver, ...
    'algorithmRevision',out.algorithmRevision,'physicalFamily',out.version, ...
    'elapsedWallTime_s',elapsed);
if isfield(out.mesh,'coarseningReport')
    execution.meshCoarsening=out.mesh.coarseningReport;
end
end
