function report=benchmark_TH_v7_recovery(checkpointFile,durationDays)
% Compare recovery from dtMin using the actual active-year checkpoint.
% This is a time-controller benchmark, not a time-discretization identity test.
root=fileparts(mfilename('fullpath')); addpath(root);
if nargin<1 || isempty(checkpointFile)
 checkpointFile=fullfile(root,'spinup60_output','active_year_checkpoint.mat');
end
if nargin<2, durationDays=.002; end
assert(isfile(checkpointFile),'Active-year checkpoint not found.');
assert(durationDays>0&&durationDays<=.1);
dtMin=86400/16384;
o=struct('meshFile',fullfile(root,'example_mesh_verified.mat'), ...
 'durationDays',durationDays,'dtInitial',dtMin,'dtMin',dtMin, ...
 'dtMax',min(.1,durationDays)*86400,'outputEveryDays',durationDays, ...
 'plot',false,'saveOutput',false,'verbose',false);
o.initial=struct('mode','checkpoint','checkpointFile',checkpointFile);
o.mechanics=struct('enable',false);
o.solver=struct('fd',1e-8,'maxIter',60,'tol',2e-8, ...
 'jacobianReuse',4,'jacobianRefreshRatio',.65);

tic; a=TH_2D_conservative_v6(o); wall6=toc;
o.solver.dtTargetResidualEvals=180; o.solver.dtGrowthSafety=1.10;
o.solver.dtGrowthMax=1.8; o.solver.dtShrinkMin=.5;
tic; b=TH_2D_conservative_v7(o); wall7=toc;
assert(all(isfinite([a.T;a.h;b.T;b.h])));

report=struct('durationDays',durationDays,'wallSecondsV6',wall6, ...
 'wallSecondsV7',wall7,'speedup',wall6/wall7, ...
 'acceptedStepsV6',size(a.history,1),'acceptedStepsV7',size(b.history,1), ...
 'medianDtSecondsV6',median(a.history(:,2))*86400, ...
 'medianDtSecondsV7',median(b.history(:,2))*86400, ...
 'residualEvaluationsV6',a.solverWork.residualEvaluations, ...
 'residualEvaluationsV7',b.solverWork.residualEvaluations, ...
 'maxResidualV6',max(a.history(:,11)),'maxResidualV7',max(b.history(:,11)), ...
 'maxAbsDeltaT',max(abs(a.T-b.T)),'maxAbsDeltaH',max(abs(a.h-b.h)));
fprintf(['v6 %.3g s/%d steps; v7 %.3g s/%d steps; speed-up %.3gx; ' ...
 'median dt %.3g -> %.3g s; |dT|max %.3g C; |dh|max %.3g m.\n'], ...
 wall6,report.acceptedStepsV6,wall7,report.acceptedStepsV7,report.speedup, ...
 report.medianDtSecondsV6,report.medianDtSecondsV7, ...
 report.maxAbsDeltaT,report.maxAbsDeltaH);
end
