function comparison=benchmark_TH_v13_scatter_30d(outputFolder)
%BENCHMARK_TH_V13_SCATTER_30D Compare local FE scatter on fast4 year-20 start.
root=fileparts(mfilename('fullpath'));
if nargin<1 || isempty(outputFolder)
    outputFolder=fullfile(root,'v13_scatter_30d_20260923');
end
if ~isfolder(outputFolder), mkdir(outputFolder); end
maxNumCompThreads(16);
s=load(fullfile(root,'segment_v11_full20_fast4_20260923','year_19.mat'),'out');
previous=s.out;
z=load(fullfile(root,'v11_refresh_30d_20260923','ratio_65_run_1.mat'),'out','elapsed_s');
reference=z.out;
p=previous.parameters;
p.mesh=previous.mesh;
p.initial=struct('mode','fields','T',previous.T,'h',previous.h,'startDay',19*365);
p.durationDays=30; p.outputEveryDays=30;
p.saveOutput=false; p.plot=false; p.verbose=false; p.mechanics.enable=false;
assert(isequal(reference.initialX,[previous.T;previous.h]));
assert(reference.parameters.dtMax==p.dtMax);
started=tic;
out=TH_2D_segment_v13(p);
elapsed_s=toc(started);
assert(isequal(out.initialX,reference.initialX));
assert(abs(out.timeDay-reference.timeDay)<1e-8);
assert(abs(sum(out.history(:,2))-30)<1e-8);
save(fullfile(outputFolder,'v13_30d.mat'),'out','elapsed_s','-v7');
leakRef=reference.leakage.totalVolume_m3_per_m;
leakNew=out.leakage.totalVolume_m3_per_m;
comparison=table(z.elapsed_s,elapsed_s,z.elapsed_s/elapsed_s, ...
    reference.solverWork.acceptedSteps,out.solverWork.acceptedSteps, ...
    reference.solverWork.rejectedSteps,out.solverWork.rejectedSteps, ...
    reference.solverWork.nonlinearIterations,out.solverWork.nonlinearIterations, ...
    reference.solverWork.jacobianBuilds,out.solverWork.jacobianBuilds, ...
    reference.solverWork.residualEvaluations,out.solverWork.residualEvaluations, ...
    1000*leakRef,1000*leakNew,100*abs(leakNew-leakRef)/max(leakRef,eps), ...
    max(abs(out.T-reference.T)),max(abs(out.h-reference.h)), ...
    max(reference.history(:,11)),max(out.history(:,11)), ...
    max(abs(reference.history(:,8))),max(abs(out.history(:,8))), ...
    max(abs(reference.history(:,9))),max(abs(out.history(:,9))), ...
    'VariableNames',{'V11Elapsed_s','V13Elapsed_s','Speedup', ...
    'V11Accepted','V13Accepted','V11Rejected','V13Rejected', ...
    'V11Newton','V13Newton','V11JacobianBuilds','V13JacobianBuilds', ...
    'V11ResidualEvaluations','V13ResidualEvaluations', ...
    'V11Leak_L_per_m','V13Leak_L_per_m','LeakRelativePercent', ...
    'MaxEndDeltaT_C','MaxEndDeltaH_m','V11MaxResidual','V13MaxResidual', ...
    'V11MaxWaterDefect_m2_per_m','V13MaxWaterDefect_m2_per_m', ...
    'V11MaxEnergyDefect_J_per_m','V13MaxEnergyDefect_J_per_m'});
writetable(comparison,fullfile(outputFolder,'comparison.csv'));
disp(comparison);
end
