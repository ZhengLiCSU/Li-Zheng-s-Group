function comparison=benchmark_v11_nonmonotone_year20(outputFolder)
%BENCHMARK_V11_NONMONOTONE_YEAR20 Compare only year 20 from identical fields.
root=fileparts(mfilename('fullpath'));
if nargin<1 || isempty(outputFolder)
    outputFolder=fullfile(root,'v11_nonmonotone_year20_20260923');
end
if ~isfolder(outputFolder), mkdir(outputFolder); end
maxNumCompThreads(16);
s=load(fullfile(root,'segment_v11_full20_fast4_20260923','year_19.mat'),'out');
previous=s.out;
p=previous.parameters; p.mesh=previous.mesh;
p.initial=struct('mode','fields','T',previous.T,'h',previous.h,'startDay',19*365);
p.durationDays=365;
p.saveOutput=false; p.plot=false; p.verbose=false; p.mechanics.enable=false;
assert(abs(p.dtMax/86400-4)<1e-12);
started=tic; baseline=TH_2D_segment_v11(p); baselineTime_s=toc(started);
fprintf('baseline year20: %.2fs, Q %.9f L/m, %d Newton, %d J\n', ...
    baselineTime_s,1000*baseline.leakage.totalVolume_m3_per_m, ...
    baseline.solverWork.nonlinearIterations,baseline.solverWork.jacobianBuilds);
started=tic; candidate=TH_2D_segment_v11_nonlinear(p); candidateTime_s=toc(started);
fprintf('candidate year20: %.2fs, Q %.9f L/m, %d Newton, %d J\n', ...
    candidateTime_s,1000*candidate.leakage.totalVolume_m3_per_m, ...
    candidate.solverWork.nonlinearIterations,candidate.solverWork.jacobianBuilds);
assert(abs(baseline.timeDay-20*365)<1e-8 && ...
    abs(candidate.timeDay-20*365)<1e-8);
hB=baseline.history; hC=candidate.history;
if size(hB,1)==size(hC,1)
    maxDtDifference_day=max(abs(hB(:,2)-hC(:,2)));
else
    maxDtDifference_day=NaN;
end
comparison=struct('baselineTime_s',baselineTime_s, ...
    'candidateTime_s',candidateTime_s,'speedup',baselineTime_s/candidateTime_s, ...
    'baselineAccepted',baseline.solverWork.acceptedSteps, ...
    'candidateAccepted',candidate.solverWork.acceptedSteps, ...
    'baselineRejected',baseline.solverWork.rejectedSteps, ...
    'candidateRejected',candidate.solverWork.rejectedSteps, ...
    'baselineNewton',baseline.solverWork.nonlinearIterations, ...
    'candidateNewton',candidate.solverWork.nonlinearIterations, ...
    'baselineJacobians',baseline.solverWork.jacobianBuilds, ...
    'candidateJacobians',candidate.solverWork.jacobianBuilds, ...
    'baselineLinearSolves',baseline.solverWork.linearSolves, ...
    'candidateLinearSolves',candidate.solverWork.linearSolves, ...
    'baselineResidualEvaluations',baseline.solverWork.residualEvaluations, ...
    'candidateResidualEvaluations',candidate.solverWork.residualEvaluations, ...
    'baselineLeak_L_per_m',1000*baseline.leakage.totalVolume_m3_per_m, ...
    'candidateLeak_L_per_m',1000*candidate.leakage.totalVolume_m3_per_m, ...
    'leakRelativeError_percent',100*abs(candidate.leakage.totalVolume_m3_per_m- ...
        baseline.leakage.totalVolume_m3_per_m)/baseline.leakage.totalVolume_m3_per_m, ...
    'baselineMaxScaledResidual',max(hB(:,11)), ...
    'candidateMaxScaledResidual',max(hC(:,11)), ...
    'baselineMaxWaterDefect_m2_per_m',max(abs(hB(:,8))), ...
    'candidateMaxWaterDefect_m2_per_m',max(abs(hC(:,8))), ...
    'baselineMaxEnergyDefect_J_per_m',max(abs(hB(:,9))), ...
    'candidateMaxEnergyDefect_J_per_m',max(abs(hC(:,9))), ...
    'endDeltaT_C',max(abs(candidate.T-baseline.T)), ...
    'endDeltaH_m',max(abs(candidate.h-baseline.h)), ...
    'maxDtDifference_day',maxDtDifference_day);
stepColumns={'endDay','dtDay','Newton','water_m2','energy_J_per_m', ...
    'Qout_m2s','Eout_W_per_m','waterDefect_m2','energyDefect_J_per_m', ...
    'leak_m2s','scaledResidual','Jacobians','linearSolves','residuals'};
writetable(array2table(hB,'VariableNames',stepColumns), ...
    fullfile(outputFolder,'baseline_steps.csv'));
writetable(array2table(hC,'VariableNames',stepColumns), ...
    fullfile(outputFolder,'candidate_steps.csv'));
writetable(struct2table(comparison),fullfile(outputFolder,'comparison.csv'));
save(fullfile(outputFolder,'year20_results.mat'),'baseline','candidate','comparison','-v7');
disp(comparison);
end
