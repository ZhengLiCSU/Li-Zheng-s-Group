function summary=probe_v11_nonlinear_30d(outputFolder,order)
%PROBE_V11_NONLINEAR_30D Log line-search behavior from the same year-19 state.
root=fileparts(mfilename('fullpath'));
if nargin<1 || isempty(outputFolder)
    outputFolder=fullfile(root,'v11_nonlinear_probe_20260923');
end
if nargin<2, order='baseline_first'; end
if ~isfolder(outputFolder), mkdir(outputFolder); end
maxNumCompThreads(16);
s=load(fullfile(root,'segment_v11_full20_fast4_20260923','year_19.mat'),'out');
previous=s.out;
p=previous.parameters;
p.mesh=previous.mesh;
p.initial=struct('mode','fields','T',previous.T,'h',previous.h,'startDay',19*365);
p.durationDays=30; p.outputEveryDays=30;
p.saveOutput=false; p.plot=false; p.verbose=false; p.mechanics.enable=false;
if strcmp(order,'candidate_first')
    started=tic; out=TH_2D_segment_v11_nonlinear(p); elapsed_s=toc(started);
    started=tic; baseline=TH_2D_segment_v11(p); baselineElapsed_s=toc(started);
else
    started=tic; baseline=TH_2D_segment_v11(p); baselineElapsed_s=toc(started);
    started=tic; out=TH_2D_segment_v11_nonlinear(p); elapsed_s=toc(started);
end
assert(abs(out.timeDay-19*365-30)<1e-8);
assert(abs(baseline.timeDay-out.timeDay)<1e-8);
maxIter=p.solver.maxIter;
rows=zeros(sum(cellfun(@(d)d.acceptedCount,out.debugNewton)),12);
cursor=0;
for sidx=1:numel(out.debugNewton)
    d=out.debugNewton{sidx}; n=d.acceptedCount;
    for iter=1:n
        cursor=cursor+1;
        rows(cursor,:)=[sidx,iter,out.history(sidx,1),out.history(sidx,2), ...
            d.acceptedLams(iter),d.initialLams(iter),d.lineSearchTrials(iter), ...
            d.thermalLams(iter),d.headLams(iter),d.contractions(iter), ...
            d.seedUsed,d.refreshOnContraction];
    end
end
assert(cursor==size(rows,1) && cursor<maxIter*numel(out.debugNewton));
iterations=array2table(rows,'VariableNames',{'Step','Iteration','EndDay','DtDay', ...
    'AcceptedLambda','InitialLambda','LineSearchTrials','ThermalBound', ...
    'HeadBound','Contraction','SeedUsed','RefreshCountForStep'});
writetable(iterations,fullfile(outputFolder,'newton_iterations.csv'));
lam=rows(:,5); lam0=rows(:,6); ls=rows(:,7);
summary=struct('Elapsed_s',elapsed_s,'AcceptedSteps',out.solverWork.acceptedSteps, ...
    'RejectedSteps',out.solverWork.rejectedSteps, ...
    'NewtonIterations',out.solverWork.nonlinearIterations, ...
    'JacobianBuilds',out.solverWork.jacobianBuilds, ...
    'LinearSolves',out.solverWork.linearSolves, ...
    'ResidualEvaluations',out.solverWork.residualEvaluations, ...
    'AcceptedLambdaMedian',median(lam),'AcceptedLambdaMin',min(lam), ...
    'AcceptedLambdaBelowQuarter',sum(lam<.25), ...
    'InitialBoundBelowOne',sum(lam0<1), ...
    'ThermalBoundActive',sum(rows(:,8)<min(1,rows(:,9))), ...
    'HeadBoundActive',sum(rows(:,9)<min(1,rows(:,8))), ...
    'LineSearchTrialsMedian',median(ls),'LineSearchTrialsMoreThanOne',sum(ls>1), ...
    'LineSearchTrialsTotal',sum(ls), ...
    'RefreshOnContraction',sum(cellfun(@(d)d.refreshOnContraction,out.debugNewton)), ...
    'StaleLineSearchFailure',sum(cellfun(@(d)d.staleFails,out.debugNewton)), ...
    'SeedUsedSteps',sum(cellfun(@(d)d.seedUsed,out.debugNewton)), ...
    'Leak_L_per_m',1000*out.leakage.totalVolume_m3_per_m, ...
    'MaxScaledResidual',max(out.history(:,11)), ...
    'MaxWaterDefect_m2_per_m',max(abs(out.history(:,8))), ...
    'MaxEnergyDefect_J_per_m',max(abs(out.history(:,9))), ...
    'BaselineElapsed_s',baselineElapsed_s, ...
    'BaselineAcceptedSteps',baseline.solverWork.acceptedSteps, ...
    'BaselineRejectedSteps',baseline.solverWork.rejectedSteps, ...
    'BaselineNewtonIterations',baseline.solverWork.nonlinearIterations, ...
    'BaselineJacobianBuilds',baseline.solverWork.jacobianBuilds, ...
    'BaselineLinearSolves',baseline.solverWork.linearSolves, ...
    'BaselineResidualEvaluations',baseline.solverWork.residualEvaluations, ...
    'BaselineLeak_L_per_m',1000*baseline.leakage.totalVolume_m3_per_m, ...
    'LeakRelativeError_percent',100*abs(out.leakage.totalVolume_m3_per_m- ...
        baseline.leakage.totalVolume_m3_per_m)/baseline.leakage.totalVolume_m3_per_m, ...
    'EndDeltaT_C',max(abs(out.T-baseline.T)), ...
    'EndDeltaH_m',max(abs(out.h-baseline.h)));
save(fullfile(outputFolder,'probe.mat'),'out','baseline','summary','-v7');
writetable(struct2table(summary),fullfile(outputFolder,'summary.csv'));
disp(summary);
end
