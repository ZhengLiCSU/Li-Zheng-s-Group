function metrics=thm_seasonal_leakage_metrics(out,relativeActivityThreshold)
%THM_SEASONAL_LEAKAGE_METRICS Integrate a complete 365-day accepted history.
% Daily volumes are exact bins of the backward-Euler accepted-step rates.
% Activity windows use a declared fraction of the daily peak; they are NOT
% physical freezing/thawing dates or a calibrated instrument detection limit.
% The far-head rate is a SAME-STATE diagnostic, not an independently solved
% ablation. Its signed difference may be negative during storage release.
if nargin<2, relativeActivityThreshold=.01; end
assert(isscalar(relativeActivityThreshold)&&isfinite(relativeActivityThreshold) ...
    &&relativeActivityThreshold>0&&relativeActivityThreshold<1, ...
    'SeasonalLeakage:Threshold','Activity threshold must be in (0,1).');
H=out.history;columns=out.historyColumns;
day=find(strcmp(columns,'day'),1);step=find(strcmp(columns,'dt_day'),1);
rate=find(strcmp(columns,'leak_m2s'),1);
assert(~isempty(day)&&~isempty(step)&&~isempty(rate)&&~isempty(H), ...
    'SeasonalLeakage:History','Accepted-step columns are required.');
endDay=H(:,day);dt=H(:,step);startDay=endDay(1)-dt(1);
assert(all(isfinite(H(:)))&&all(dt>0)&&all(diff(endDay)>0) ...
    &&max(abs(diff([startDay;endDay])-dt))<1e-7 ...
    &&abs(endDay(end)-startDay-365)<1e-7 ...
    &&abs(startDay/365-round(startDay/365))<1e-8, ...
    'SeasonalLeakage:History','One complete aligned 365-day year with no gaps is required.');
actual=H(:,rate);byJoint=out.leakage.jointRate_m2_per_s;
body=out.leakage.bodyRate_m2_per_s;
assert(all(actual>=0)&&all(byJoint(:)>=0)&&all(body==0) ...
    &&size(byJoint,1)==numel(actual) ...
    &&max(abs(sum(byJoint,2)-actual))<1e-12, ...
    'SeasonalLeakage:Balance','Joint-only rates must sum to the conservative total.');
potential=sum(out.leakage.hydraulics.unrestrictedRate_m2_per_s,2);
assert(numel(potential)==numel(actual)&&all(isfinite(potential))&&all(potential>=0), ...
    'SeasonalLeakage:Potential','Same-state far-head rates are required.');
knots=[startDay;endDay];edges=startDay+(0:365)';seconds=dt*86400;
bins=@(r) diff(interp1(knots,[zeros(1,size(r,2));cumsum(r.*seconds,1)],edges,'linear'),1,1);
daily=1000*bins(actual);unrestricted=1000*bins(potential);joints=1000*bins(byJoint);
Q=sum(daily);[peak,peakDay]=max(daily);active=daily>relativeActivityThreshold*peak;
if peak==0, peakDay=NaN; end
starts=find(diff([false;active])==1);ends=find(diff([active;false])==-1);
windows=table(starts,ends,ends-starts+1,'VariableNames',{'firstDay','lastDay','duration_days'});
first=NaN;last=NaN;
if ~isempty(starts), first=starts(1);last=ends(end); end
monthly=zeros(12,1);edgesMonth=[0 cumsum([31 28 31 30 31 30 31 31 30 31 30 31])];
for m=1:12, monthly(m)=sum(daily(edgesMonth(m)+1:edgesMonth(m+1))); end
assert(abs(Q-1000*out.leakage.totalVolume_m3_per_m)<1e-8, ...
    'SeasonalLeakage:Integral','Independent annual integration disagrees with the saved result.');
fraction=NaN;if sum(unrestricted)>0, fraction=(sum(unrestricted)-Q)/sum(unrestricted);end
metrics=struct('schemaVersion',1,'startDay',startDay,'annual_L_m',Q, ...
    'monthly_L_m',monthly,'jointAnnual_L_m',sum(joints,1), ...
    'daily',table((1:365)',daily,unrestricted,unrestricted-daily, ...
    'VariableNames',{'dayOfYear','actual_L_m','sameStateFarHead_L_m','signedSupplyDeficit_L_m'}), ...
    'peakDaily_L_m',peak,'peakDailyDay',peakDay,'firstActiveDay',first, ...
    'lastActiveDay',last,'activityThresholdFractionOfPeak',relativeActivityThreshold, ...
    'activeDays',sum(active),'activityWindows',windows, ...
    'sameStateFarHeadAnnual_L_m',sum(unrestricted), ...
    'signedSupplyDeficitFraction',fraction,'acceptedSteps',out.solverWork.acceptedSteps, ...
    'rejectedSteps',out.solverWork.rejectedSteps, ...
    'scope','Full-year numerical metrics; activity is threshold-defined, far-head comparison is same-state, not causal isolation.');
end
