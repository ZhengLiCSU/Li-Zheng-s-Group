function report = diagnose_thermo_interface_domain(z,model,p)
%DIAGNOSE_THERMO_INTERFACE_DOMAIN Evidence, not a cavitation constitutive law.
% An almost fully frozen, pressure-limited cell with a positive gap requires
% a void/gas/debonding extension before continued extrapolation is justified.
s=thermo_interface_state(z,model,p);
nearLimit=s.pressure-p.minimumPressure_Pa<10;
frozen=s.fraction>1-1e-6;
limited=find(nearLimit);
report=struct('minimumPressure_Pa',min(s.pressure),'pressureLowerBound_Pa',p.minimumPressure_Pa, ...
    'pressureLimitedCells',limited,'fullyFrozenPressureLimitedCells',find(nearLimit&frozen), ...
    'cellTable',[(1:numel(s.pressure))',s.pressure,s.fraction,s.x(:,4)-273.15,s.x(:,1),s.x(:,2)], ...
    'columns',{{'cell','pressure_Pa','iceMassFraction','temperature_C','gapIncrement_m','mass_kgm2'}}, ...
    'classification','not_at_pressure_domain_boundary', ...
    'interpretation','This diagnostic does not establish a calibrated cavitation or fracture threshold.');
if ~isempty(limited)
    report.classification='saturated_single_pressure_domain_exhausted';
    report.interpretation=['The accepted solution has approached the prescribed tensile-pressure applicability bound. ' ...
        'Further time-step reduction cannot supply a missing void/gas/ice-wall separation law. ' ...
        'Preserve this failed run; do not clip pressure, refill mass, or label it a completed cycle.'];
end
end
