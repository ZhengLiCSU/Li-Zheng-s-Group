function report=audit_TH_v10_year20(folder)
%AUDIT_TH_V10_YEAR20 Independently verify saved 20-year TH continuation.
root=fileparts(mfilename('fullpath'));
if nargin<1 || isempty(folder)
    folder=fullfile(root,'segment_v10_iteration_stress20_20260923');
end
tableFile=fullfile(folder,'yearly_step_audit.csv');
assert(isfile(tableFile),'Missing annual audit CSV.');
yearly=readtable(tableFile);
assert(height(yearly)==20 && isequal(yearly.Year,(1:20)'), ...
    'The annual audit must contain exactly years 1 to 20.');
saved=load(fullfile(folder,'spinup_progress.mat'),'progress');
assert(saved.progress.completedYears==20, ...
    'The annual checkpoint has not reached year 20.');
maxRestartGap=0; maxWaterDefect=0; maxEnergyDefect=0;
maxScaledResidual=0; nonOutputShort=zeros(20,1);
previous=[];
for year=1:20
    item=load(fullfile(folder,sprintf('year_%02d.mat',year)),'out');
    out=item.out; h=out.history;
    assert(strcmp(out.version,'TH_v10_20260923_iteration_dt'));
    assert(abs(out.timeDay-365*year)<1e-7);
    assert(size(h,2)==14 && abs(sum(h(:,2))-365)<1e-6 && ...
        all(diff(h(:,1))>0) && abs(h(end,1)-365*year)<1e-7);
    assert(numel(out.snapshots)==12,'Incomplete monthly snapshot history.');
    assert(out.solverWork.acceptedSteps==size(h,1));
    assert(abs(out.leakage.totalVolume_m3_per_m- ...
        sum(h(:,10).*h(:,2))*86400)<1e-10, ...
        'Annual leakage does not equal integrated step rates.');
    assert(abs(yearly.Leak_L_per_m(year)- ...
        1000*out.leakage.totalVolume_m3_per_m)<1e-8);
    assert(yearly.Accepted(year)==size(h,1) && ...
        yearly.Rejected(year)==out.solverWork.rejectedSteps);
    if ~isempty(previous)
        restartGap=max(abs(out.initialX-[previous.T;previous.h]));
        maxRestartGap=max(maxRestartGap,restartGap);
        assert(restartGap<1e-12,'Discontinuous field between annual runs.');
    end
    phase=(h(:,1)-365*(year-1))/(365/12);
    interior=abs(phase-round(phase))>=1e-8;
    nonOutputShort(year)=sum(h(:,2)<.1 & interior);
    assert(yearly.InteriorBelow_0p1d(year)==nonOutputShort(year));
    maxWaterDefect=max(maxWaterDefect,max(abs(h(:,8))));
    maxEnergyDefect=max(maxEnergyDefect,max(abs(h(:,9))));
    maxScaledResidual=max(maxScaledResidual,max(h(:,11)));
    previous=out;
end
assert(isequal(saved.progress.lastYear.T,previous.T) && ...
    isequal(saved.progress.lastYear.h,previous.h), ...
    'Year-20 checkpoint and archived result differ.');
report=struct('completedYears',20,'year20Leak_L_per_m',yearly.Leak_L_per_m(20), ...
    'year20Accepted',yearly.Accepted(20), ...
    'year20Rejected',yearly.Rejected(20), ...
    'year20MinimumDt_day',yearly.MinDt_day(20), ...
    'year20NonOutputShortSteps',nonOutputShort(20), ...
    'allYearsNonOutputShortSteps',sum(nonOutputShort), ...
    'maximumAnnualAcceptedSteps',max(yearly.Accepted), ...
    'maximumAnnualRejectedSteps',max(yearly.Rejected), ...
    'maximumRestartGap',maxRestartGap, ...
    'maximumStepWaterDefect_m2_per_m',maxWaterDefect, ...
    'maximumStepEnergyDefect_J_per_m',maxEnergyDefect, ...
    'maximumScaledResidual',maxScaledResidual);
save(fullfile(folder,'postrun_validation.mat'),'report','-v7');
disp(report);
end
