classdef TestTHMAnnualContinuation < matlab.unittest.TestCase
    %TESTTHMANNUALCONTINUATION Installed THM reference survives year resume.
    % A sealed, saturated, constant-4-C annulus is an equilibrium continuation
    % check rather than a freeze-thaw calibration or a 20-year benchmark.

    methods (Test)
        function annualCheckpointPreservesEntireCoupledStateAndReference(testCase)
            report=TestTHMAnnualContinuation.exerciseContinuation();
            testCase.verifyEqual(report.pausedYears,1);
            testCase.verifyEqual(report.pausedStatus,'paused_at_year_boundary');
            testCase.verifyEqual(report.completedYears,2);
            testCase.verifyEqual(report.schemaVersion,11);
            testCase.verifyEqual(report.lastTimeDay,730,'AbsTol',1e-7);
            testCase.verifyEqual(report.firstReferenceU,report.secondReferenceU,'AbsTol',0);
            testCase.verifyEqual(report.firstReferenceT,report.secondReferenceT,'AbsTol',0);
            testCase.verifyEqual(report.firstFinalX,report.secondInitialX,'AbsTol',0);
            testCase.verifyEqual(report.secondFinalX,report.secondCheckpointX,'AbsTol',0);
            testCase.verifyEqual(report.initialMode,'checkpoint');
            testCase.verifyEqual(report.referenceT,4*ones(size(report.referenceT)),'AbsTol',0);
            testCase.verifyEqual(report.firstTemperature,report.secondTemperature,'AbsTol',2e-7);
            testCase.verifyEqual(report.firstHead,report.secondHead,'AbsTol',2e-7);
            testCase.verifyEqual(report.annualRows,2);
            testCase.verifyEqual(report.monthlyRows,24);
            testCase.verifyEqual(report.jointRows,16);
            testCase.verifyEqual(report.dailyRows,730);
            testCase.verifyEqual(report.yearDurationDays,365,'AbsTol',1e-6);
            testCase.verifyEqual(report.mechanicalHistoryRows,report.acceptedSteps);
            testCase.verifyEqual(report.checkpointMechanicalHistoryRows,report.acceptedSteps);
            testCase.verifyEqual(report.year2Leak_m3_per_m,0,'AbsTol',0);
            testCase.verifyTrue(report.year20Absent);
            testCase.verifyTrue(report.partialResumeSupported);
            testCase.verifyEqual(report.initialCheckpointFile,report.firstCheckpointFile);
        end
    end

    methods (Static,Access=private)
        function report=exerciseContinuation()
            root=fileparts(mfilename('fullpath')); addpath(root);
            parent=fullfile(root,'thm_annual_continuation_checks');
            if ~isfolder(parent), mkdir(parent); end
            folder=tempname(parent); mkdir(folder);
            marker=fullfile(folder,'PAUSE_AFTER_YEAR');
            fid=fopen(marker,'w'); assert(fid>=0,'Cannot create pause marker.'); fclose(fid);
            model=struct('mesh',make_thm_verification_mesh(16),'dtInitial',4*86400, ...
                'dtMax',4*86400,'waterTableDepth',-2,'topSeepage',false, ...
                'geothermalFlux',0,'topMin',4,'topMax',4,'tunnelMin',4,'tunnelMax',4, ...
                'groundwaterInflowT',4,'groundwaterInflowGradient',0, ...
                'initial',struct('mode','profile','surfaceT',4,'gradient',0), ...
                'leakage',struct('jointConductance',zeros(1,8)), ...
                'thm',struct('enabled',true));
            user=struct('outputFolder',folder,'maxYears',2,'model',model);
            paused=run_TH_segment_year20_jointonly(user);
            first=paused.lastYear;
            delete(marker);
            user.resume=true;
            resumed=run_TH_segment_year20_jointonly(user);
            second=resumed.lastYear;
            cp1=load(resumed.coreCheckpoints{1},'checkpoint');
            cp2=load(resumed.coreCheckpoints{2},'checkpoint','mechanicalHistory');
            report=struct('outputFolder',folder,'pausedYears',paused.completedYears, ...
                'pausedStatus',paused.status,'completedYears',resumed.completedYears, ...
                'schemaVersion',resumed.schemaVersion,'lastTimeDay',second.timeDay, ...
                'firstReferenceU',cp1.checkpoint.mechanicalReference.U, ...
                'secondReferenceU',cp2.checkpoint.mechanicalReference.U, ...
                'firstReferenceT',cp1.checkpoint.mechanicalReference.T, ...
                'secondReferenceT',cp2.checkpoint.mechanicalReference.T, ...
                'firstFinalX',first.finalX,'secondInitialX',second.initialX, ...
                'secondFinalX',second.finalX,'secondCheckpointX',cp2.checkpoint.X, ...
                'initialMode',second.parameters.initial.mode, ...
                'referenceT',second.mechanics.referenceTemperature, ...
                'firstTemperature',first.T,'secondTemperature',second.T, ...
                'firstHead',first.h,'secondHead',second.h, ...
                'annualRows',size(resumed.annual,1),'monthlyRows',size(resumed.monthly,1), ...
                'jointRows',size(resumed.byJoint,1),'dailyRows',size(resumed.daily,1), ...
                'yearDurationDays',sum(second.history(:,2)), ...
                'mechanicalHistoryRows',size(second.mechanics.history,1), ...
                'checkpointMechanicalHistoryRows',size(cp2.mechanicalHistory,1), ...
                'acceptedSteps',second.solverWork.acceptedSteps, ...
                'year2Leak_m3_per_m',second.leakage.totalVolume_m3_per_m, ...
                'year20Absent',isnan(resumed.year20AnnualLeakage_L_per_m), ...
                'partialResumeSupported',resumed.partialYearResumeSupported, ...
                'initialCheckpointFile',second.parameters.initial.checkpointFile, ...
                'firstCheckpointFile',resumed.coreCheckpoints{1});
            save(fullfile(folder,'annual_continuation_verification.mat'),'report','-v7');
            fprintf('THM annual continuation verification folder: %s.\n',folder);
        end
    end
end
